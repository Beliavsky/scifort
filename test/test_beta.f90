        end do
    end subroutine test_beta_distribution_reference

    subroutine test_endpoints(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        call check_true('beta pdf 0, a < 1', beta_pdf(0.0_dp, 0.5_dp, 2.0_dp) > huge(1.0_dp), &
            failures)
        call check_close('beta pdf 0, a = 1', beta_pdf(0.0_dp, 1.0_dp, 3.0_dp), 3.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('beta pdf 0, a > 1', beta_pdf(0.0_dp, 2.0_dp, 3.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('beta pdf 1, b < 1', beta_pdf(1.0_dp, 1.0_dp, 0.5_dp) > huge(1.0_dp), &
            failures)
        call check_close('beta pdf 1, b = 1, scaled', &
            beta_pdf(5.0_dp, 2.0_dp, 1.0_dp, 1.0_dp, 4.0_dp), 0.5_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('beta pdf outside', beta_pdf(1.5_dp, 2.0_dp, 3.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('beta cdf at 1', beta_cdf(1.0_dp, 2.0_dp, 3.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('beta logsf at 1', beta_logsf(1.0_dp, 2.0_dp, 3.0_dp) < -huge(1.0_dp), &
            failures)
        call check_close('beta ppf 0', beta_ppf(0.0_dp, 2.0_dp, 3.0_dp, 1.0_dp, 4.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('beta ppf 1', beta_ppf(1.0_dp, 2.0_dp, 3.0_dp, 1.0_dp, 4.0_dp), &
            5.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('beta isf 0', beta_isf(0.0_dp, 2.0_dp, 3.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)

        call check_close('t cdf 0', t_cdf(3.0_dp, 4.0_dp, 3.0_dp), 0.5_dp, 0.0_dp, 0.0_dp, &
            failures)
        call check_close('t cdf -inf', t_cdf(negative_inf, 4.0_dp), 0.0_dp, 0.0_dp, &
            0.0_dp, failures)
        call check_close('t sf -inf', t_sf(negative_inf, 4.0_dp), 1.0_dp, 0.0_dp, &
            0.0_dp, failures)
        call check_close('t pdf inf', t_pdf(positive_inf, 4.0_dp), 0.0_dp, 0.0_dp, &
            0.0_dp, failures)
        call check_true('t ppf 0', t_ppf(0.0_dp, 4.0_dp) < -huge(1.0_dp), failures)
        call check_true('t isf 0', t_isf(0.0_dp, 4.0_dp) > huge(1.0_dp), failures)
        call check_close('t ppf 1/2', t_ppf(0.5_dp, 4.0_dp, 2.0_dp), 2.0_dp, 0.0_dp, &
            0.0_dp, failures)

        call check_true('F pdf 0, dfn < 2', f_pdf(0.0_dp, 1.0_dp, 5.0_dp) > huge(1.0_dp), &
            failures)
        call check_close('F pdf 0, dfn = 2', f_pdf(0.0_dp, 2.0_dp, 5.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('F pdf 0, dfn > 2', f_pdf(0.0_dp, 3.0_dp, 5.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('F cdf inf', f_cdf(positive_inf, 3.0_dp, 5.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('F ppf 0', f_ppf(0.0_dp, 3.0_dp, 5.0_dp, 2.0_dp), 2.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('F isf 0', f_isf(0.0_dp, 3.0_dp, 5.0_dp) > huge(1.0_dp), failures)
    end subroutine test_endpoints

    subroutine test_invalid_and_ieee(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        call check_true('beta zero shape', ieee_is_nan(beta_cdf(0.5_dp, 0.0_dp, 1.0_dp)), &
            failures)
        call check_true('beta infinite shape', &
            ieee_is_nan(beta_pdf(0.5_dp, 1.0_dp, positive_inf)), failures)
        call check_true('beta NaN x', ieee_is_nan(beta_sf(nan_value, 2.0_dp, 2.0_dp)), &
            failures)
        call check_true('beta ppf p < 0', ieee_is_nan(beta_ppf(-0.1_dp, 2.0_dp, 2.0_dp)), &
            failures)
        call check_true('t zero df', ieee_is_nan(t_cdf(1.0_dp, 0.0_dp)), failures)
        call check_true('t NaN df', ieee_is_nan(t_pdf(1.0_dp, nan_value)), failures)
        call check_true('t NaN x', ieee_is_nan(t_logsf(nan_value, 3.0_dp)), failures)
        call check_true('t zero scale', ieee_is_nan(t_cdf(1.0_dp, 3.0_dp, scale=0.0_dp)), &
            failures)
        call check_true('t ppf p > 1', ieee_is_nan(t_ppf(1.5_dp, 3.0_dp)), failures)
        call check_true('F infinite dfd', ieee_is_nan(f_cdf(1.0_dp, 2.0_dp, positive_inf)), &
            failures)
        call check_true('F negative dfn', ieee_is_nan(f_pdf(1.0_dp, -2.0_dp, 3.0_dp)), &
            failures)
        call check_true('F NaN x', ieee_is_nan(f_logcdf(nan_value, 2.0_dp, 3.0_dp)), &
            failures)
    end subroutine test_invalid_and_ieee

    ! Exact limits of the Cauchy case df = 1: sf(t) = atan(1/t) / pi and
    ! ppf(p) = -1 / tan(pi p), both of which reduce to 1 / (pi t) far out.
    subroutine test_extreme_tails(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        call check_close('t sf 1e200, df 1', t_sf(1.0e200_dp, 1.0_dp), &
            1.0_dp / (scifort_pi * 1.0e200_dp), 0.0_dp, 1.0e-14_dp, failures)
        call check_close('t logcdf -1e200, df 1', t_logcdf(-1.0e200_dp, 1.0_dp), &
            -log(scifort_pi) - 200.0_dp * log(10.0_dp), 0.0_dp, 1.0e-14_dp, failures)
        call check_close('t ppf 1e-300, df 1', t_ppf(1.0e-300_dp, 1.0_dp), &
            -1.0_dp / (scifort_pi * 1.0e-300_dp), 0.0_dp, 1.0e-13_dp, failures)
        call check_close('t isf 1e-300, df 3', t_sf(t_isf(1.0e-300_dp, 3.0_dp), 3.0_dp), &
            1.0e-300_dp, 0.0_dp, 1.0e-12_dp, failures)
    end subroutine test_extreme_tails

    subroutine test_monotonicity(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        logical :: ok
        real(dp) :: previous
        real(dp) :: value
        real(dp) :: x

        ok = .true.
        previous = 0.0_dp
        do i = -400, 400
            x = sign(10.0_dp ** (abs(real(i, dp)) / 100.0_dp), real(i, dp))
            value = t_cdf(x, 2.5_dp)
            ok = ok .and. value >= previous .and. value <= 1.0_dp
            previous = value
        end do
        call check_true('t cdf monotone', ok, failures)

        ok = .true.
        previous = 0.0_dp
        do i = -600, 600
            x = 10.0_dp ** (real(i, dp) / 100.0_dp)
            value = f_cdf(x, 3.0_dp, 7.0_dp)
            ok = ok .and. value >= previous .and. value <= 1.0_dp
            previous = value
        end do
        call check_true('F cdf monotone', ok, failures)

        ok = .true.
        previous = 0.0_dp
        do i = 1, 999
            x = real(i, dp) / 1000.0_dp
            value = beta_cdf(x, 0.7_dp, 300.0_dp)
            ok = ok .and. value >= previous .and. value <= 1.0_dp .and. &
                beta_pdf(x, 0.7_dp, 300.0_dp) >= 0.0_dp
            previous = value
        end do
        call check_true('beta cdf monotone', ok, failures)
    end subroutine test_monotonicity

    ! A quantile carries a relative error of order eps, which moves a tail V
    ! by about eps x f(x) / V; the forward function adds eps (1 + |log V|).
    ! A quantile that underflows to zero, overflows, or rounds to the upper
    ! support endpoint cannot reproduce p; the test then checks that this is
    ! justified.
    subroutine test_round_trips(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        real(dp), parameter :: probabilities(6) = [1.0e-100_dp, 1.0e-8_dp, 0.025_dp, &
            0.3_dp, 0.5_dp, 0.99_dp]
        real(dp), parameter :: dfs(5) = [0.5_dp, 1.0_dp, 3.0_dp, 40.0_dp, 1.0e5_dp]
        integer :: i
        integer :: j
        real(dp) :: p
        real(dp) :: rtol
        real(dp) :: x

        do i = 1, size(dfs)
            do j = 1, size(probabilities)
                p = probabilities(j)
                x = t_ppf(p, dfs(i))
                rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + abs(x) * t_pdf(x, dfs(i)) / p)
                call check_close('t cdf(ppf(p))', t_cdf(x, dfs(i)), p, 0.0_dp, rtol, failures)
                x = f_ppf(p, dfs(i), 7.0_dp)
                if (x == 0.0_dp) then
                    call check_true('F ppf underflow is justified', &
                        f_cdf(tiny(1.0_dp), dfs(i), 7.0_dp) >= p, failures)
                else
                    rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + &
                        x * f_pdf(x, dfs(i), 7.0_dp) / p)
                    call check_close('F cdf(ppf(p))', f_cdf(x, dfs(i), 7.0_dp), p, 0.0_dp, &
                        rtol, failures)
                end if
                x = f_isf(p, 7.0_dp, dfs(i))
                if (.not. ieee_is_finite(x)) then
                    call check_true('F isf overflow is justified', &
                        f_sf(huge(1.0_dp), 7.0_dp, dfs(i)) >= p, failures)
                else
                    rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + &
                        x * f_pdf(x, 7.0_dp, dfs(i)) / p)
                    call check_close('F sf(isf(p))', f_sf(x, 7.0_dp, dfs(i)), p, 0.0_dp, &
                        rtol, failures)
                end if
                x = beta_isf(p, dfs(i), 2.0_dp)
                if (x == 1.0_dp) then
                    ! The exact root lies above the largest double below one.
                    call check_true('beta isf rounding to 1 is justified', &
                        beta_sf(1.0_dp - epsilon(1.0_dp) / 2.0_dp, dfs(i), 2.0_dp) >= p, &
                        failures)
                else
                    rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + &
                        x * beta_pdf(x, dfs(i), 2.0_dp) / p)
                    call check_close('beta sf(isf(p))', beta_sf(x, dfs(i), 2.0_dp), p, &
                        0.0_dp, rtol, failures)
                end if
            end do
        end do
    end subroutine test_round_trips

    subroutine test_distribution_identities(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        real(dp) :: t(6)

        t = [-50.0_dp, -2.0_dp, -0.1_dp, 0.3_dp, 4.0_dp, 1.0e6_dp]
        do i = 1, size(t)
            call check_close('t(1) cdf = Cauchy', t_cdf(t(i), 1.0_dp), cauchy_cdf(t(i)), &
                0.0_dp, 4.0_dp * eps, failures)
            call check_close('t(1) logsf = Cauchy', t_logsf(t(i), 1.0_dp), &
                cauchy_logsf(t(i)), 0.0_dp, 4.0_dp * eps, failures)
            ! Closed form for df = 2: cdf = 1/2 + t / (2 sqrt(2 + t**2)).
            call check_close('t(2) closed form', t_cdf(t(i), 2.0_dp), &
                0.5_dp + t(i) / (2.0_dp * sqrt(2.0_dp + t(i)**2)), 1.0e-16_dp, 1.0e-14_dp, &
                failures)
            call check_close('t(inf) = normal', t_cdf(t(i), positive_inf, 1.0_dp, 2.0_dp), &
                normal_cdf(t(i), 1.0_dp, 2.0_dp), 0.0_dp, 0.0_dp, failures)
            ! F(1, df) is the distribution of the square of t(df).
            call check_close('F(1, df) = t squared', f_sf(t(i)**2, 1.0_dp, 6.0_dp), &
                2.0_dp * t_sf(abs(t(i)), 6.0_dp), 0.0_dp, 1.0e-14_dp, failures)
            call check_close('t pdf symmetry', t_pdf(t(i), 3.5_dp), t_pdf(-t(i), 3.5_dp), &
                0.0_dp, 0.0_dp, failures)
            call check_close('t cdf + sf', t_cdf(t(i), 3.5_dp) + t_sf(t(i), 3.5_dp), 1.0_dp, &
                2.0_dp * eps, 0.0_dp, failures)
        end do

        call check_close('beta(1, 1) = uniform', beta_cdf(2.6_dp, 1.0_dp, 1.0_dp, 2.0_dp, &
            3.0_dp), uniform_cdf(2.6_dp, 2.0_dp, 3.0_dp), 0.0_dp, 4.0_dp * eps, failures)
        call check_close('beta ppf symmetry', beta_ppf(0.2_dp, 3.0_dp, 5.0_dp), &
            1.0_dp - beta_ppf(0.8_dp, 5.0_dp, 3.0_dp), 1.0e-15_dp, 0.0_dp, failures)
        call check_close('t ppf symmetry', t_ppf(0.01_dp, 7.0_dp), -t_isf(0.01_dp, 7.0_dp), &
            0.0_dp, 0.0_dp, failures)
    end subroutine test_distribution_identities

    subroutine test_elemental(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        real(dp) :: actual(4)
        real(dp) :: x(4)

        x = [0.1_dp, 0.4_dp, 0.7_dp, 0.95_dp]
        actual = betainc(2.0_dp, 5.0_dp, x)
        do i = 1, size(x)
            call check_close('betainc elemental', actual(i), betainc(2.0_dp, 5.0_dp, x(i)), &
                0.0_dp, 0.0_dp, failures)
        end do
        actual = t_cdf(x, [1.0_dp, 2.0_dp, 5.0_dp, 30.0_dp])
        call check_close('t cdf elemental', actual(3), t_cdf(x(3), 5.0_dp), 0.0_dp, &
            0.0_dp, failures)
        actual = f_ppf(x, 3.0_dp, 9.0_dp)
        call check_close('F ppf elemental', actual(4), f_ppf(x(4), 3.0_dp, 9.0_dp), &
            0.0_dp, 0.0_dp, failures)
    end subroutine test_elemental

