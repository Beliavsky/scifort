        do i = 1, size(st_x)
            write(label, '(a,i0)') 't logpdf reference ', i
            call check_close(trim(label), t_logpdf(st_x(i), st_df(i)), st_logpdf(i), &
                st_tol_logpdf(i), 0.0_dp, failures)
            write(label, '(a,i0)') 't cdf reference ', i
            call check_close(trim(label), t_cdf(st_x(i), st_df(i)), st_cdf(i), &
                st_tol_cdf(i), 0.0_dp, failures)
            write(label, '(a,i0)') 't sf reference ', i
            call check_close(trim(label), t_sf(st_x(i), st_df(i)), st_sf(i), &
                st_tol_sf(i), 0.0_dp, failures)
            write(label, '(a,i0)') 't logcdf reference ', i
            call check_close(trim(label), t_logcdf(st_x(i), st_df(i)), log(st_cdf(i)), &
                st_tol_cdf(i) / st_cdf(i), 0.0_dp, failures)
            write(label, '(a,i0)') 't logsf reference ', i
            call check_close(trim(label), t_logsf(st_x(i), st_df(i)), log(st_sf(i)), &
                st_tol_sf(i) / st_sf(i), 0.0_dp, failures)
        end do
    end subroutine test_t_reference

