! Tests for the incomplete beta function and the beta, Student t, and F
! distributions. Reference values are generated by
! tools/generate_beta_reference.py.

program test_beta
    use, intrinsic :: ieee_arithmetic, only : ieee_is_finite, ieee_is_nan, &
        ieee_negative_inf, ieee_positive_inf, ieee_quiet_nan, ieee_value
    use scifort_constants, only : scifort_pi
    use scifort_special, only : betainc, betaincc, betainccinv, betaincinv
    use scifort_stats
    use test_beta_reference
    use test_checks, only : check_close, check_true
    implicit none

    real(dp), parameter :: eps = epsilon(1.0_dp)
    integer :: failures
    real(dp) :: nan_value
    real(dp) :: negative_inf
    real(dp) :: positive_inf

    nan_value = ieee_value(0.0_dp, ieee_quiet_nan)
    negative_inf = ieee_value(0.0_dp, ieee_negative_inf)
    positive_inf = ieee_value(0.0_dp, ieee_positive_inf)

    failures = 0
    call test_betainc_reference(failures)
    call test_betainc_special_values(failures)
    call test_betainc_identities(failures)
    call test_inverse_reference(failures)
    call test_t_reference(failures)
    call test_f_reference(failures)
    call test_beta_distribution_reference(failures)
    call test_endpoints(failures)
    call test_invalid_and_ieee(failures)
    call test_extreme_tails(failures)
    call test_monotonicity(failures)
    call test_round_trips(failures)
    call test_distribution_identities(failures)
    call test_elemental(failures)

    if (failures == 0) then
        print '(a)', 'test_beta: PASS'
    else
        print '(a,1x,i0)', 'test_beta: FAIL', failures
        error stop 1
    end if

contains

    subroutine test_betainc_reference(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        character(len=64) :: label

        do i = 1, size(ib_a)
            write(label, '(a,i0)') 'betainc reference ', i
            call check_close(trim(label), betainc(ib_a(i), ib_b(i), ib_x(i)), ib_p(i), &
                ib_tol_p(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'betaincc reference ', i
            call check_close(trim(label), betaincc(ib_a(i), ib_b(i), ib_x(i)), ib_q(i), &
                ib_tol_q(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'beta logcdf reference ', i
            call check_close(trim(label), beta_logcdf(ib_x(i), ib_a(i), ib_b(i)), &
                ib_logp(i), ib_tol_logp(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'beta logsf reference ', i
            call check_close(trim(label), beta_logsf(ib_x(i), ib_a(i), ib_b(i)), &
                ib_logq(i), ib_tol_logq(i), 0.0_dp, failures)
        end do
    end subroutine test_betainc_reference

    ! Conventions follow scipy.special.betainc: a and b must be finite and
    ! positive and 0 <= x <= 1.
    subroutine test_betainc_special_values(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        call check_close('betainc(1, 1, 0)', betainc(1.0_dp, 1.0_dp, 0.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('betainc(1, 1, 1)', betainc(1.0_dp, 1.0_dp, 1.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('betaincc(2, 3, 0)', betaincc(2.0_dp, 3.0_dp, 0.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('betaincc(2, 3, 1)', betaincc(2.0_dp, 3.0_dp, 1.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('betainc(0, 1, 0.5)', ieee_is_nan(betainc(0.0_dp, 1.0_dp, 0.5_dp)), &
            failures)
        call check_true('betainc(1, -1, 0.5)', &
            ieee_is_nan(betainc(1.0_dp, -1.0_dp, 0.5_dp)), failures)
        call check_true('betainc(inf, 1, 0.5)', &
            ieee_is_nan(betainc(positive_inf, 1.0_dp, 0.5_dp)), failures)
        call check_true('betainc(1, 1, 1.5)', ieee_is_nan(betainc(1.0_dp, 1.0_dp, 1.5_dp)), &
            failures)
        call check_true('betaincc NaN x', ieee_is_nan(betaincc(1.0_dp, 1.0_dp, nan_value)), &
            failures)
        call check_close('betaincinv(1, 1, 0)', betaincinv(1.0_dp, 1.0_dp, 0.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('betaincinv(1, 1, 1)', betaincinv(1.0_dp, 1.0_dp, 1.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('betainccinv(1, 1, 0)', betainccinv(1.0_dp, 1.0_dp, 0.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('betainccinv(1, 1, 1)', betainccinv(1.0_dp, 1.0_dp, 1.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('betaincinv(0, 1, 0.5)', &
            ieee_is_nan(betaincinv(0.0_dp, 1.0_dp, 0.5_dp)), failures)
        call check_true('betainccinv p > 1', &
            ieee_is_nan(betainccinv(2.0_dp, 3.0_dp, 1.5_dp)), failures)
    end subroutine test_betainc_special_values

    subroutine test_betainc_identities(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: j
        integer :: m
        integer :: n
        real(dp) :: binomial
        real(dp) :: coefficient
        real(dp) :: x

        ! x and 1 - x are both exact in binary64.
        x = 0.25_dp
        call check_close('I_x(1, 1) = x', betainc(1.0_dp, 1.0_dp, x), x, 0.0_dp, &
            2.0_dp * eps, failures)
        call check_close('I_x(a, 1) = x**a', betainc(3.7_dp, 1.0_dp, x), x**3.7_dp, &
            0.0_dp, 8.0_dp * eps, failures)
        call check_close('1 - I_x(1, b) = (1 - x)**b', betaincc(1.0_dp, 2.5_dp, x), &
            (1.0_dp - x)**2.5_dp, 0.0_dp, 8.0_dp * eps, failures)
        call check_close('symmetry DLMF 8.17.4', betainc(2.5_dp, 7.0_dp, x), &
            betaincc(7.0_dp, 2.5_dp, 1.0_dp - x), 0.0_dp, 4.0_dp * eps, failures)

        ! DLMF 8.17.5: I_x(m, n - m + 1) = sum over j = m..n of C(n, j) x**j (1 - x)**(n - j).
        n = 12
        do m = 1, n
            binomial = 0.0_dp
            coefficient = 1.0_dp
            do j = 0, n
                if (j > 0) coefficient = coefficient * real(n - j + 1, dp) / real(j, dp)
                if (j >= m) binomial = binomial + coefficient * x**j * (1.0_dp - x)**(n - j)
            end do
            call check_close('binomial sum DLMF 8.17.5', &
                betainc(real(m, dp), real(n - m + 1, dp), x), binomial, 0.0_dp, &
                1.0e-14_dp, failures)
        end do
    end subroutine test_betainc_identities

