                ibinv_x(i), ibinv_tol(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'betainccinv reference ', i
            call check_close(trim(label), betainccinv(ibinv_a(i), ibinv_b(i), ibinv_p(i)), &
                ibcinv_x(i), ibcinv_tol(i), 0.0_dp, failures)
        end do
    end subroutine test_inverse_reference

    subroutine test_t_reference(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
