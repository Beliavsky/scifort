    end subroutine test_f_reference

    subroutine test_beta_distribution_reference(failures)
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        character(len=64) :: label

        do i = 1, size(bd_x)
            write(label, '(a,i0)') 'beta logpdf reference ', i
            call check_close(trim(label), &
                beta_logpdf(bd_x(i), bd_a(i), bd_b(i), bd_loc(i), bd_scale(i)), &
