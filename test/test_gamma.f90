    subroutine test_monotonicity(failures)
        integer, intent(inout) :: failures

        real(dp), parameter :: shapes(6) = [1.0e-3_dp, 0.3_dp, 1.0_dp, 2.5_dp, &
            40.0_dp, 5000.0_dp]
        integer :: i
        integer :: j
        logical :: ok
        real(dp) :: cdf_prev
        real(dp) :: cdf_now
        real(dp) :: pdf_now
        real(dp) :: sf_now
        real(dp) :: sf_prev
        real(dp) :: x

        ok = .true.
        do i = 1, size(shapes)
            cdf_prev = 0.0_dp
            sf_prev = 1.0_dp
            do j = -600, 800
                x = 10.0_dp ** (real(j, dp) / 100.0_dp)
                cdf_now = gamma_cdf(x, shapes(i))
                sf_now = gamma_sf(x, shapes(i))
                pdf_now = gamma_pdf(x, shapes(i))
                ok = ok .and. cdf_now >= cdf_prev .and. sf_now <= sf_prev
                ok = ok .and. cdf_now >= 0.0_dp .and. cdf_now <= 1.0_dp
                ok = ok .and. sf_now >= 0.0_dp .and. sf_now <= 1.0_dp
                ok = ok .and. pdf_now >= 0.0_dp
                cdf_prev = cdf_now
                sf_prev = sf_now
            end do
        end do
        call check_true('gamma monotone and bounded', ok, failures)
    end subroutine test_monotonicity

    ! Round-trip tolerance: a quantile x carries a relative rounding error of
    ! order eps, which moves a tail probability V by eps * x f(x) / V; the
    ! forward function adds eps * (1 + |log V|).
    subroutine test_round_trips(failures)
        integer, intent(inout) :: failures

        real(dp), parameter :: shapes(7) = [1.0e-3_dp, 0.3_dp, 1.0_dp, 2.5_dp, &
            30.0_dp, 1000.0_dp, 1.0e5_dp]
        real(dp), parameter :: probabilities(7) = [1.0e-300_dp, 1.0e-12_dp, &
            0.01_dp, 0.3_dp, 0.5_dp, 0.9_dp, 1.0_dp - 1.0e-10_dp]
        integer :: i
        integer :: j
        real(dp) :: a
        real(dp) :: p
        real(dp) :: rtol
        real(dp) :: x

        do i = 1, size(shapes)
            a = shapes(i)
            do j = 1, size(probabilities)
                p = probabilities(j)

                x = gamma_ppf(p, a)
                if (x == 0.0_dp) then
                    call check_true('gamma ppf underflow is justified', &
                        gamma_cdf(tiny(1.0_dp), a) >= p, failures)
                else
                    rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + &
                        x * gamma_pdf(x, a) / p)
                    call check_close('gamma cdf(ppf(p))', gamma_cdf(x, a), p, &
                        0.0_dp, rtol, failures)
                end if

                x = gamma_isf(p, a)
                if (x == 0.0_dp) then
                    call check_true('gamma isf underflow is justified', &
                        gamma_sf(tiny(1.0_dp), a) <= p, failures)
                else
                    rtol = 20.0_dp * eps * (1.0_dp + abs(log(p)) + &
                        x * gamma_pdf(x, a) / p)
                    call check_close('gamma sf(isf(p))', gamma_sf(x, a), p, &
                        0.0_dp, rtol, failures)
                end if
            end do
        end do

        ! Reference from mpmath 1.3.0 at 40 digits.
        x = chi2_ppf(0.95_dp, 1.0_dp)
        call check_close('chi2 ppf 0.95 df 1', x, 3.8414588206941259584_dp, 0.0_dp, &
            1.0e-14_dp, failures)
    end subroutine test_round_trips

    subroutine test_distribution_identities(failures)
        integer, intent(inout) :: failures

        integer :: i
        real(dp) :: x(6)

        x = [1.0e-8_dp, 0.3_dp, 1.0_dp, 4.0_dp, 30.0_dp, 600.0_dp]
        do i = 1, size(x)
            call check_close('gamma(1) cdf = exponential', &
                gamma_cdf(x(i), 1.0_dp, 0.5_dp, 2.0_dp), &
                exponential_cdf(x(i), 0.5_dp, 2.0_dp), 0.0_dp, 4.0_dp * eps, failures)
            call check_close('gamma(1) sf = exponential', &
                gamma_sf(x(i), 1.0_dp), exponential_sf(x(i)), 0.0_dp, &
                1.0e-14_dp, failures)
            call check_close('gamma(1) logsf = exponential', &
                gamma_logsf(x(i), 1.0_dp), exponential_logsf(x(i)), 0.0_dp, &
                4.0_dp * eps, failures)
            call check_close('gamma(1) logpdf = exponential', &
                gamma_logpdf(x(i), 1.0_dp), exponential_logpdf(x(i)), 0.0_dp, &
                4.0_dp * eps, failures)
            call check_close('chi2(2) cdf = exponential(scale 2)', &
                chi2_cdf(x(i), 2.0_dp), exponential_cdf(x(i), scale=2.0_dp), &
                0.0_dp, 4.0_dp * eps, failures)
            call check_close('chi2 = gamma(df/2, scale 2)', &
                chi2_sf(x(i), 7.0_dp, 1.0_dp, 3.0_dp), &
                gamma_sf(x(i), 3.5_dp, 1.0_dp, 6.0_dp), 0.0_dp, 0.0_dp, failures)
            call check_close('gamma cdf + sf', gamma_cdf(x(i), 3.3_dp) + &
                gamma_sf(x(i), 3.3_dp), 1.0_dp, 2.0_dp * eps, 0.0_dp, failures)
            call check_close('chi2(1) cdf = erf', chi2_cdf(x(i), 1.0_dp), &
                erf(sqrt(0.5_dp * x(i))), 0.0_dp, 8.0_dp * eps, failures)
        end do
    end subroutine test_distribution_identities

    subroutine test_elemental(failures)
        integer, intent(inout) :: failures

        integer :: i
        real(dp) :: actual(4)
        real(dp) :: p(4)
        real(dp) :: x(4)

        x = [0.1_dp, 1.0_dp, 5.0_dp, 20.0_dp]
        actual = gamma_cdf(x, 2.5_dp, scale=1.5_dp)
        do i = 1, size(x)
            call check_close('gamma cdf elemental', actual(i), &
                gamma_cdf(x(i), 2.5_dp, scale=1.5_dp), 0.0_dp, 0.0_dp, failures)
        end do

        p = [0.01_dp, 0.25_dp, 0.5_dp, 0.99_dp]
        actual = chi2_ppf(p, [1.0_dp, 2.0_dp, 5.0_dp, 50.0_dp])
        call check_close('chi2 ppf elemental 1', actual(1), chi2_ppf(p(1), 1.0_dp), &
            0.0_dp, 0.0_dp, failures)
        call check_close('chi2 ppf elemental 4', actual(4), chi2_ppf(p(4), 50.0_dp), &
            0.0_dp, 0.0_dp, failures)

        actual = gammainc([0.5_dp, 1.0_dp, 2.0_dp, 4.0_dp], 2.0_dp)
        call check_close('gammainc elemental', actual(3), gammainc(2.0_dp, 2.0_dp), &
            0.0_dp, 0.0_dp, failures)
    end subroutine test_elemental

end program test_gamma
