! Tests for the incomplete gamma functions, the gamma and chi-square
! distributions, and the elementary helpers they depend on. Reference values
! are generated by tools/generate_gamma_reference.py.

program test_gamma
    use, intrinsic :: ieee_arithmetic, only : ieee_is_nan, &
        ieee_negative_inf, ieee_positive_inf, ieee_quiet_nan, ieee_value
    use scifort_incomplete_gamma, only : log_gammainc, log_gammaincc
    use scifort_math, only : expm1_safe, log1p_safe
    use scifort_special, only : gammainc, gammaincc, gammainccinv, gammaincinv
    use scifort_stats
    use test_checks, only : check_close, check_true
    use test_gamma_reference
    implicit none

    real(dp), parameter :: eps = epsilon(1.0_dp)
    integer :: failures
    real(dp) :: nan_value
    real(dp) :: negative_inf
    real(dp) :: positive_inf

    nan_value = ieee_value(0.0_dp, ieee_quiet_nan)
    negative_inf = ieee_value(0.0_dp, ieee_negative_inf)
    positive_inf = ieee_value(0.0_dp, ieee_positive_inf)

    failures = 0
    call test_elementary(failures)
    call test_incomplete_gamma_reference(failures)
    call test_incomplete_gamma_special_values(failures)
    call test_incomplete_gamma_identities(failures)
    call test_inverse_reference(failures)
    call test_gamma_reference_values(failures)
    call test_chi2_reference_values(failures)
    call test_endpoints(failures)
    call test_invalid_and_ieee(failures)
    call test_monotonicity(failures)
    call test_round_trips(failures)
    call test_distribution_identities(failures)
    call test_elemental(failures)

    if (failures == 0) then
        print '(a)', 'test_gamma: PASS'
    else
        print '(a,1x,i0)', 'test_gamma: FAIL', failures
        error stop 1
    end if

contains

    ! Reference values from mpmath 1.3.0 at 40 digits.
    subroutine test_elementary(failures)
        integer, intent(inout) :: failures

        call check_close('log1p 1e-300', log1p_safe(1.0e-300_dp), 1.0e-300_dp, &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('log1p 1e-10', log1p_safe(1.0e-10_dp), &
            9.9999999995e-11_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('log1p 1e-4', log1p_safe(1.0e-4_dp), &
            0.000099995000333308335333_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('log1p -0.3', log1p_safe(-0.3_dp), &
            -0.35667494393873237891_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('log1p 0.75', log1p_safe(0.75_dp), &
            0.55961578793542268627_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('log1p -0.999', log1p_safe(-0.999_dp), &
            -6.9077552789821370521_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_true('log1p -1', log1p_safe(-1.0_dp) < -huge(1.0_dp), failures)
        call check_true('log1p below -1', ieee_is_nan(log1p_safe(-2.0_dp)), failures)
        call check_true('log1p NaN', ieee_is_nan(log1p_safe(nan_value)), failures)
        call check_true('log1p infinity', log1p_safe(positive_inf) > huge(1.0_dp), &
            failures)

        call check_close('expm1 1e-300', expm1_safe(1.0e-300_dp), 1.0e-300_dp, &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('expm1 1e-10', expm1_safe(1.0e-10_dp), &
            1.00000000005e-10_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('expm1 1e-5', expm1_safe(1.0e-5_dp), &
            0.000010000050000166667083_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('expm1 -0.4', expm1_safe(-0.4_dp), &
            -0.32967995396436069926_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('expm1 0.49', expm1_safe(0.49_dp), &
            0.63231621995537897012_dp, 0.0_dp, 2.0_dp * eps, failures)
        call check_close('expm1 3', expm1_safe(3.0_dp), &
            19.085536923187667741_dp, 0.0_dp, 4.0_dp * eps, failures)
        call check_close('expm1 -infinity', expm1_safe(negative_inf), -1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('expm1 NaN', ieee_is_nan(expm1_safe(nan_value)), failures)
    end subroutine test_elementary

    subroutine test_incomplete_gamma_reference(failures)
        integer, intent(inout) :: failures

        integer :: i
        character(len=64) :: label

        do i = 1, size(ig_a)
            write(label, '(a,i0)') 'gammainc reference ', i
            call check_close(trim(label), gammainc(ig_a(i), ig_x(i)), ig_p(i), &
                ig_tol_p(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'gammaincc reference ', i
            call check_close(trim(label), gammaincc(ig_a(i), ig_x(i)), ig_q(i), &
                ig_tol_q(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'log_gammainc reference ', i
            call check_close(trim(label), log_gammainc(ig_a(i), ig_x(i)), &
                ig_logp(i), ig_tol_logp(i), 0.0_dp, failures)
            write(label, '(a,i0)') 'log_gammaincc reference ', i
            call check_close(trim(label), log_gammaincc(ig_a(i), ig_x(i)), &
                ig_logq(i), ig_tol_logq(i), 0.0_dp, failures)
        end do
    end subroutine test_incomplete_gamma_reference

    ! Conventions follow scipy.special.gammainc and gammaincc.
    subroutine test_incomplete_gamma_special_values(failures)
        integer, intent(inout) :: failures

        call check_close('gammainc(0, 1)', gammainc(0.0_dp, 1.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('gammaincc(0, 1)', gammaincc(0.0_dp, 1.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('gammainc(0, 0)', ieee_is_nan(gammainc(0.0_dp, 0.0_dp)), &
            failures)
        call check_close('gammainc(1, 0)', gammainc(1.0_dp, 0.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('gammaincc(1, 0)', gammaincc(1.0_dp, 0.0_dp), 1.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_close('gammainc(1, inf)', gammainc(1.0_dp, positive_inf), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('gammaincc(1, inf)', gammaincc(1.0_dp, positive_inf), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('gammainc(inf, 1)', gammainc(positive_inf, 1.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('gammaincc(inf, 1)', gammaincc(positive_inf, 1.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('gammainc(inf, inf)', &
            ieee_is_nan(gammainc(positive_inf, positive_inf)), failures)
        call check_true('gammainc(-1, 1)', ieee_is_nan(gammainc(-1.0_dp, 1.0_dp)), &
            failures)
        call check_true('gammaincc(1, -1)', ieee_is_nan(gammaincc(1.0_dp, -1.0_dp)), &
            failures)
        call check_true('gammainc NaN a', ieee_is_nan(gammainc(nan_value, 1.0_dp)), &
            failures)
        call check_true('gammaincc NaN x', ieee_is_nan(gammaincc(1.0_dp, nan_value)), &
            failures)
        call check_true('log_gammainc(1, 0)', &
            log_gammainc(1.0_dp, 0.0_dp) < -huge(1.0_dp), failures)
        call check_close('log_gammaincc(1, 0)', log_gammaincc(1.0_dp, 0.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)

        call check_close('gammaincinv(1, 0)', gammaincinv(1.0_dp, 0.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('gammaincinv(1, 1)', gammaincinv(1.0_dp, 1.0_dp) > huge(1.0_dp), &
            failures)
        call check_true('gammainccinv(1, 0)', &
            gammainccinv(1.0_dp, 0.0_dp) > huge(1.0_dp), failures)
        call check_close('gammainccinv(1, 1)', gammainccinv(1.0_dp, 1.0_dp), 0.0_dp, &
            0.0_dp, 0.0_dp, failures)
        call check_true('gammaincinv(0, 0.5)', &
            ieee_is_nan(gammaincinv(0.0_dp, 0.5_dp)), failures)
        call check_true('gammaincinv(1, 1.5)', &
            ieee_is_nan(gammaincinv(1.0_dp, 1.5_dp)), failures)
        call check_true('gammainccinv(1, NaN)', &
            ieee_is_nan(gammainccinv(1.0_dp, nan_value)), failures)
        ! The root is about 1e-353000, which rounds to zero.
        call check_close('gammaincinv underflow', gammaincinv(1.0e-3_dp, 0.3_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
    end subroutine test_incomplete_gamma_special_values

    subroutine test_incomplete_gamma_identities(failures)
        integer, intent(inout) :: failures

        integer :: k
        integer :: n
        real(dp) :: poisson_sum
        real(dp) :: term
        real(dp) :: x

        ! Q(n + 1, x) is the Poisson probability of at most n events.
        x = 3.7_dp
        do n = 0, 12
            term = exp(-x)
            poisson_sum = term
            do k = 1, n
                term = term * x / real(k, dp)
                poisson_sum = poisson_sum + term
            end do
            call check_close('Poisson identity', gammaincc(real(n + 1, dp), x), &
                poisson_sum, 0.0_dp, 1.0e-14_dp, failures)
        end do

        ! P(1/2, x) = erf(sqrt(x)) and Q(1/2, x) = erfc(sqrt(x)).
        call check_close('P(1/2, 2) = erf', gammainc(0.5_dp, 2.0_dp), &
            erf(sqrt(2.0_dp)), 0.0_dp, 4.0_dp * eps, failures)
        call check_close('Q(1/2, 50) = erfc', gammaincc(0.5_dp, 50.0_dp), &
            erfc(sqrt(50.0_dp)), 0.0_dp, 1.0e-14_dp, failures)
    end subroutine test_incomplete_gamma_identities

