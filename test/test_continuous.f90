! Tests for the lognormal, weibull, pareto, and rayleigh distributions.
! Reference values are generated by tools/generate_continuous_reference.py.

program test_continuous
    use, intrinsic :: ieee_arithmetic, only : ieee_is_finite, ieee_is_nan, &
        ieee_negative_inf, ieee_positive_inf, ieee_quiet_nan, ieee_value
    use scifort_constants, only : scifort_sqrt_two
    use scifort_kinds, only : dp
    use scifort_stats
    use test_checks, only : check_close, check_true
    use test_continuous_reference
    implicit none

    real(dp), parameter :: eps = epsilon(1.0_dp)
    integer :: failures
    real(dp) :: nan_value
    real(dp) :: negative_inf
    real(dp) :: positive_inf

    nan_value = ieee_value(0.0_dp, ieee_quiet_nan)
    negative_inf = ieee_value(0.0_dp, ieee_negative_inf)
    positive_inf = ieee_value(0.0_dp, ieee_positive_inf)

    failures = 0
    call test_lognormal_reference(failures)
    call test_weibull_reference(failures)
    call test_pareto_reference(failures)
    call test_rayleigh_reference(failures)
    call test_endpoints(failures)
    call test_round_trips(failures)
    call test_identities(failures)
    call test_invalid_and_ieee(failures)
    call test_elemental(failures)

    if (failures == 0) then
        print '(a)', 'test_continuous: PASS'
    else
        print '(a,1x,i0)', 'test_continuous: FAIL', failures
        error stop 1
    end if

contains

    subroutine test_lognormal_reference(failures)
        ! Compares lognormal functions against high-precision reference values.
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        character(len=64) :: label

        do i = 1, size(ln_x)
            write(label, '(a,i0)') 'lognormal pdf ref ', i
            call check_close(trim(label), lognormal_pdf(ln_x(i), ln_s(i)), ln_pdf(i), &
                ln_tol(i) * ln_pdf(i), ln_tol(i), failures)

            write(label, '(a,i0)') 'lognormal cdf ref ', i
            call check_close(trim(label), lognormal_cdf(ln_x(i), ln_s(i)), ln_cdf(i), &
                ln_tol(i) * ln_cdf(i), ln_tol(i), failures)

            write(label, '(a,i0)') 'lognormal sf ref ', i
            call check_close(trim(label), lognormal_sf(ln_x(i), ln_s(i)), ln_sf(i), &
                ln_tol(i) * ln_sf(i), ln_tol(i), failures)

            write(label, '(a,i0)') 'lognormal logcdf ref ', i
            call check_close(trim(label), lognormal_logcdf(ln_x(i), ln_s(i)), ln_logcdf(i), &
                ln_tol(i), ln_tol(i), failures)

            write(label, '(a,i0)') 'lognormal logsf ref ', i
            call check_close(trim(label), lognormal_logsf(ln_x(i), ln_s(i)), ln_logsf(i), &
                ln_tol(i), ln_tol(i), failures)
        end do
    end subroutine test_lognormal_reference

