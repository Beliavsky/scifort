    subroutine test_endpoints(failures)
        ! Checks boundary, support endpoint, and quantile endpoint behaviors.
        integer, intent(inout) :: failures !! running count of failed checks

        ! Lognormal endpoints
        call check_close('lognormal pdf 0', lognormal_pdf(0.0_dp, 1.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('lognormal cdf 0', lognormal_cdf(0.0_dp, 1.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('lognormal sf 0', lognormal_sf(0.0_dp, 1.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('lognormal ppf 0', lognormal_ppf(0.0_dp, 1.0_dp, loc=2.0_dp), &
            2.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('lognormal ppf 1 is inf', &
            .not. ieee_is_finite(lognormal_ppf(1.0_dp, 1.0_dp)) .and. &
            lognormal_ppf(1.0_dp, 1.0_dp) > 0.0_dp, failures)
        call check_close('lognormal isf 1', lognormal_isf(1.0_dp, 1.0_dp, loc=2.0_dp), &
            2.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('lognormal isf 0 is inf', &
            .not. ieee_is_finite(lognormal_isf(0.0_dp, 1.0_dp)) .and. &
            lognormal_isf(0.0_dp, 1.0_dp) > 0.0_dp, failures)

        ! Weibull endpoints
        call check_close('weibull cdf 0', weibull_cdf(0.0_dp, 1.5_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('weibull sf 0', weibull_sf(0.0_dp, 1.5_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('weibull pdf 0 c<1 is inf', &
            .not. ieee_is_finite(weibull_pdf(0.0_dp, 0.5_dp)) .and. &
            weibull_pdf(0.0_dp, 0.5_dp) > 0.0_dp, failures)
        call check_close('weibull pdf 0 c=1', weibull_pdf(0.0_dp, 1.0_dp, scale=2.0_dp), &
            0.5_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('weibull pdf 0 c>1', weibull_pdf(0.0_dp, 2.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('weibull ppf 0', weibull_ppf(0.0_dp, 1.5_dp, loc=3.0_dp), &
            3.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('weibull ppf 1 is inf', &
            .not. ieee_is_finite(weibull_ppf(1.0_dp, 1.5_dp)) .and. &
            weibull_ppf(1.0_dp, 1.5_dp) > 0.0_dp, failures)
        call check_close('weibull isf 1', weibull_isf(1.0_dp, 1.5_dp, loc=3.0_dp), &
            3.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('weibull isf 0 is inf', &
            .not. ieee_is_finite(weibull_isf(0.0_dp, 1.5_dp)) .and. &
            weibull_isf(0.0_dp, 1.5_dp) > 0.0_dp, failures)

        ! Pareto endpoints
        call check_close('pareto cdf 1', pareto_cdf(1.0_dp, 2.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('pareto sf 1', pareto_sf(1.0_dp, 2.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('pareto pdf 1', pareto_pdf(1.0_dp, 2.0_dp, scale=2.0_dp, loc=0.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('pareto pdf loc+scale', pareto_pdf(3.0_dp, 2.0_dp, loc=1.0_dp, scale=2.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('pareto ppf 0', pareto_ppf(0.0_dp, 2.0_dp, loc=1.0_dp, scale=2.0_dp), &
            3.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('pareto ppf 1 is inf', &
            .not. ieee_is_finite(pareto_ppf(1.0_dp, 2.0_dp)) .and. &
            pareto_ppf(1.0_dp, 2.0_dp) > 0.0_dp, failures)
        call check_close('pareto isf 1', pareto_isf(1.0_dp, 2.0_dp, loc=1.0_dp, scale=2.0_dp), &
            3.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('pareto isf 0 is inf', &
            .not. ieee_is_finite(pareto_isf(0.0_dp, 2.0_dp)) .and. &
            pareto_isf(0.0_dp, 2.0_dp) > 0.0_dp, failures)

        ! Rayleigh endpoints
        call check_close('rayleigh pdf 0', rayleigh_pdf(0.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('rayleigh cdf 0', rayleigh_cdf(0.0_dp), &
            0.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('rayleigh sf 0', rayleigh_sf(0.0_dp), &
            1.0_dp, 0.0_dp, 0.0_dp, failures)
        call check_close('rayleigh ppf 0', rayleigh_ppf(0.0_dp, loc=1.5_dp), &
            1.5_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('rayleigh ppf 1 is inf', &
            .not. ieee_is_finite(rayleigh_ppf(1.0_dp)) .and. &
            rayleigh_ppf(1.0_dp) > 0.0_dp, failures)
        call check_close('rayleigh isf 1', rayleigh_isf(1.0_dp, loc=1.5_dp), &
            1.5_dp, 0.0_dp, 0.0_dp, failures)
        call check_true('rayleigh isf 0 is inf', &
            .not. ieee_is_finite(rayleigh_isf(0.0_dp)) .and. &
            rayleigh_isf(0.0_dp) > 0.0_dp, failures)
    end subroutine test_endpoints

    subroutine test_round_trips(failures)
        ! Checks that cdf(ppf(p)) == p and sf(isf(p)) == p.
        integer, intent(inout) :: failures !! running count of failed checks

        integer :: i
        real(dp) :: p(7)
        real(dp) :: q
        character(len=64) :: label

        p = [1.0e-6_dp, 0.01_dp, 0.1_dp, 0.5_dp, 0.9_dp, 0.99_dp, 1.0_dp - 1.0e-6_dp]

        do i = 1, size(p)
            q = p(i)
            write(label, '(a,i0)') 'lognormal cdf ppf round trip ', i
            call check_close(trim(label), lognormal_cdf(lognormal_ppf(q, 0.75_dp), 0.75_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)
            write(label, '(a,i0)') 'lognormal sf isf round trip ', i
            call check_close(trim(label), lognormal_sf(lognormal_isf(q, 0.75_dp), 0.75_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)

            write(label, '(a,i0)') 'weibull cdf ppf round trip ', i
            call check_close(trim(label), weibull_cdf(weibull_ppf(q, 1.5_dp), 1.5_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)
            write(label, '(a,i0)') 'weibull sf isf round trip ', i
            call check_close(trim(label), weibull_sf(weibull_isf(q, 1.5_dp), 1.5_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)

            write(label, '(a,i0)') 'pareto cdf ppf round trip ', i
            call check_close(trim(label), pareto_cdf(pareto_ppf(q, 2.5_dp), 2.5_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)
            write(label, '(a,i0)') 'pareto sf isf round trip ', i
            call check_close(trim(label), pareto_sf(pareto_isf(q, 2.5_dp), 2.5_dp), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)

            write(label, '(a,i0)') 'rayleigh cdf ppf round trip ', i
            call check_close(trim(label), rayleigh_cdf(rayleigh_ppf(q)), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)
            write(label, '(a,i0)') 'rayleigh sf isf round trip ', i
            call check_close(trim(label), rayleigh_sf(rayleigh_isf(q)), &
                q, 1.0e-15_dp, 1.0e-14_dp, failures)
        end do
    end subroutine test_round_trips

    subroutine test_identities(failures)
        ! Checks analytical relationships between distributions.
        integer, intent(inout) :: failures !! running count of failed checks

        real(dp) :: x

        ! Weibull(c=1, loc, scale) == Exponential(loc, scale)
        x = 1.5_dp
        call check_close('weibull c=1 is expon pdf', &
            weibull_pdf(x, 1.0_dp, loc=0.5_dp, scale=2.0_dp), &
            exponential_pdf(x, loc=0.5_dp, scale=2.0_dp), &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('weibull c=1 is expon cdf', &
            weibull_cdf(x, 1.0_dp, loc=0.5_dp, scale=2.0_dp), &
            exponential_cdf(x, loc=0.5_dp, scale=2.0_dp), &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('weibull c=1 is expon sf', &
            weibull_sf(x, 1.0_dp, loc=0.5_dp, scale=2.0_dp), &
            exponential_sf(x, loc=0.5_dp, scale=2.0_dp), &
            0.0_dp, 2.0_dp * eps, failures)

        ! Weibull(c=2, loc, scale = sqrt(2)*sigma) == Rayleigh(loc, sigma)
        call check_close('weibull c=2 is rayleigh pdf', &
            weibull_pdf(x, 2.0_dp, loc=0.2_dp, scale=scifort_sqrt_two * 1.5_dp), &
            rayleigh_pdf(x, loc=0.2_dp, scale=1.5_dp), &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('weibull c=2 is rayleigh cdf', &
            weibull_cdf(x, 2.0_dp, loc=0.2_dp, scale=scifort_sqrt_two * 1.5_dp), &
            rayleigh_cdf(x, loc=0.2_dp, scale=1.5_dp), &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('weibull c=2 is rayleigh sf', &
            weibull_sf(x, 2.0_dp, loc=0.2_dp, scale=scifort_sqrt_two * 1.5_dp), &
            rayleigh_sf(x, loc=0.2_dp, scale=1.5_dp), &
            0.0_dp, 2.0_dp * eps, failures)

        ! Lognormal(s, loc=0, scale=1) at exp(z) CDF matches Normal(0, s) at z
        call check_close('lognormal normal cdf identity', &
            lognormal_cdf(exp(1.2_dp), 0.8_dp), &
            normal_cdf(1.2_dp, 0.0_dp, 0.8_dp), &
            0.0_dp, 2.0_dp * eps, failures)
        call check_close('lognormal normal sf identity', &
            lognormal_sf(exp(1.2_dp), 0.8_dp), &
            normal_sf(1.2_dp, 0.0_dp, 0.8_dp), &
            0.0_dp, 2.0_dp * eps, failures)
    end subroutine test_identities

    subroutine test_invalid_and_ieee(failures)
        ! Checks invalid parameters and IEEE values return quiet NaN.
        integer, intent(inout) :: failures !! running count of failed checks

        ! Invalid shape
        call check_true('lognormal invalid s <= 0', ieee_is_nan(lognormal_pdf(1.0_dp, 0.0_dp)), failures)
        call check_true('lognormal invalid s negative', ieee_is_nan(lognormal_pdf(1.0_dp, -1.0_dp)), failures)
        call check_true('weibull invalid c <= 0', ieee_is_nan(weibull_pdf(1.0_dp, 0.0_dp)), failures)
        call check_true('pareto invalid b <= 0', ieee_is_nan(pareto_pdf(2.0_dp, 0.0_dp)), failures)

        ! Invalid scale
        call check_true('lognormal invalid scale <= 0', ieee_is_nan(lognormal_pdf(1.0_dp, 1.0_dp, scale=0.0_dp)), failures)
        call check_true('weibull invalid scale <= 0', ieee_is_nan(weibull_pdf(1.0_dp, 1.0_dp, scale=-1.0_dp)), failures)
        call check_true('pareto invalid scale <= 0', ieee_is_nan(pareto_pdf(2.0_dp, 1.0_dp, scale=0.0_dp)), failures)
        call check_true('rayleigh invalid scale <= 0', ieee_is_nan(rayleigh_pdf(1.0_dp, scale=0.0_dp)), failures)

        ! Invalid probability
        call check_true('lognormal ppf < 0', ieee_is_nan(lognormal_ppf(-0.1_dp, 1.0_dp)), failures)
        call check_true('lognormal ppf > 1', ieee_is_nan(lognormal_ppf(1.1_dp, 1.0_dp)), failures)
        call check_true('weibull ppf < 0', ieee_is_nan(weibull_ppf(-0.1_dp, 1.0_dp)), failures)
        call check_true('weibull ppf > 1', ieee_is_nan(weibull_ppf(1.1_dp, 1.0_dp)), failures)
        call check_true('pareto ppf < 0', ieee_is_nan(pareto_ppf(-0.1_dp, 1.0_dp)), failures)
        call check_true('pareto ppf > 1', ieee_is_nan(pareto_ppf(1.1_dp, 1.0_dp)), failures)
        call check_true('rayleigh ppf < 0', ieee_is_nan(rayleigh_ppf(-0.1_dp)), failures)
        call check_true('rayleigh ppf > 1', ieee_is_nan(rayleigh_ppf(1.1_dp)), failures)

        ! NaN input
        call check_true('lognormal nan x', ieee_is_nan(lognormal_pdf(nan_value, 1.0_dp)), failures)
        call check_true('weibull nan x', ieee_is_nan(weibull_pdf(nan_value, 1.0_dp)), failures)
        call check_true('pareto nan x', ieee_is_nan(pareto_pdf(nan_value, 1.0_dp)), failures)
        call check_true('rayleigh nan x', ieee_is_nan(rayleigh_pdf(nan_value)), failures)
    end subroutine test_invalid_and_ieee

    subroutine test_elemental(failures)
        ! Checks that array and scalar evaluations agree.
        integer, intent(inout) :: failures !! running count of failed checks

        real(dp) :: x(3)
        real(dp) :: y(3)
        integer :: i

        x = [0.5_dp, 1.0_dp, 2.0_dp]

        ! Lognormal elemental
        y = lognormal_pdf(x, 1.0_dp)
        do i = 1, 3
            call check_close('lognormal elemental', y(i), lognormal_pdf(x(i), 1.0_dp), &
                0.0_dp, 0.0_dp, failures)
        end do

        ! Weibull elemental
        y = weibull_cdf(x, 1.5_dp)
        do i = 1, 3
            call check_close('weibull elemental', y(i), weibull_cdf(x(i), 1.5_dp), &
                0.0_dp, 0.0_dp, failures)
        end do

        ! Pareto elemental
        y = pareto_sf(x + 1.0_dp, 2.0_dp)
        do i = 1, 3
            call check_close('pareto elemental', y(i), pareto_sf(x(i) + 1.0_dp, 2.0_dp), &
                0.0_dp, 0.0_dp, failures)
        end do

        ! Rayleigh elemental
        y = rayleigh_cdf(x)
        do i = 1, 3
            call check_close('rayleigh elemental', y(i), rayleigh_cdf(x(i)), &
                0.0_dp, 0.0_dp, failures)
        end do
    end subroutine test_elemental

end program test_continuous
