#!/usr/bin/env python3
"""Generate SciPy 1.17 SR1 trust-constr reference optimizers for Fortran tests."""

from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import Bounds, NonlinearConstraint, SR1, minimize


def double_well(x):
    return (x[0] ** 2 - 1.0) ** 2 + 0.5 * (x[1] - 0.3) ** 2


def double_well_grad(x):
    return np.array([4.0 * x[0] ** 3 - 4.0 * x[0], x[1] - 0.3])


def quadratic(x):
    return np.sum((x - 1.2) ** 2)


def quadratic_grad(x):
    return 2.0 * (x - 1.2)


def circle(x):
    return np.array([np.sum(x ** 2)])


def circle_jac(x):
    return np.array([2.0 * x])


def circle_hess(x, v):
    return 2.0 * v[0] * np.eye(x.size)


circle_equal = NonlinearConstraint(circle, 1.0, 1.0, jac=circle_jac)
circle_upper = NonlinearConstraint(circle, -np.inf, 1.0, jac=circle_jac, hess=circle_hess)

scenarios = {
    "double_well": dict(fun=double_well, x0=[0.4, 1.0], jac=double_well_grad),
    "double_well_fd": dict(fun=double_well, x0=[0.4, 1.0], jac="3-point"),
    "equality": dict(fun=quadratic, x0=[0.2, 0.2], jac=quadratic_grad,
                     constraints=[circle_equal]),
    "bounds": dict(fun=quadratic, x0=[0.0, 0.0], jac=quadratic_grad,
                   bounds=Bounds([-np.inf, -np.inf], [0.5, 0.75])),
    "barrier": dict(fun=quadratic, x0=[0.2, 0.2], jac=quadratic_grad,
                    constraints=[circle_upper],
                    bounds=Bounds([0.0, 0.0], [np.inf, np.inf])),
}

out = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_sr1_reference.py",
    f"! SciPy version: {scipy.__version__}",
    "module test_optimize_trust_constr_sr1_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for name, parameters in scenarios.items():
    res = minimize(method="trust-constr", hess=SR1(),
                   options={"gtol": 1.0e-9, "maxiter": 400}, **parameters)
    if not res.success:
        raise RuntimeError((name, res.status, res.message))
    if res.nhev != 0:
        raise RuntimeError((name, "unexpected analytic Hessian evaluations"))
    values = ", ".join(f"{value:.17e}_dp" for value in res.x)
    out.append(f"    real(dp), parameter :: {name}_x({len(res.x)}) = [ &")
    out.append(f"        {values} ]")
    out.append(f"    real(dp), parameter :: {name}_fun = {res.fun:.17e}_dp")
    print(f"{name}: x={res.x} nit={res.nit} fun={res.fun:.12g} status={res.status}")
out.append("end module test_optimize_trust_constr_sr1_reference")

output_file = Path(__file__).resolve().parent.parent / "test/optimize_trust_constr_sr1_reference.f90"
output_file.write_text("\n".join(out) + "\n", encoding="ascii")
print("Generated:", output_file)
