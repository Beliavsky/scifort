#!/usr/bin/env python3
"""Generate overdetermined trust-constr reference data using SciPy SVD projection."""

from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import Bounds, LinearConstraint, NonlinearConstraint, minimize


def objective(x):
    return (x[0] - 0.1) ** 2 + 2.0 * (x[1] - 0.3) ** 2


def gradient(x):
    return np.array([2.0 * (x[0] - 0.1), 4.0 * (x[1] - 0.3)])


def hessian(x):
    return np.diag([2.0, 4.0])


def nonlinear_values(x):
    norm_sq = np.dot(x, x)
    return np.array([norm_sq - 5.0, 2.0 * norm_sq - 10.0, x[0] - x[1] - 1.0])


def nonlinear_jacobian(x):
    return np.array([[2.0 * x[0], 2.0 * x[1]],
                     [4.0 * x[0], 4.0 * x[1]], [1.0, -1.0]])


def nonlinear_hessian(x, v):
    return 2.0 * (v[0] + 2.0 * v[1]) * np.eye(2)


matrix = np.array([[1.0, 1.0], [2.0, 2.0], [1.0, -1.0]])
rhs = np.array([3.0, 6.0, 1.0])
scenarios = {
    "linear": dict(x0=[0.0, 0.0], constraints=[LinearConstraint(matrix, rhs, rhs)]),
    "bounded": dict(x0=[0.0, 0.0], constraints=[
        LinearConstraint(matrix[:2], rhs[:2], rhs[:2]),
        LinearConstraint(matrix[2:], rhs[2:], rhs[2:])],
        bounds=Bounds([0.0, 0.0], [np.inf, np.inf])),
    "nonlinear": dict(x0=[1.8, 0.8], constraints=[NonlinearConstraint(
        nonlinear_values, 0.0, 0.0, jac=nonlinear_jacobian,
        hess=nonlinear_hessian)]),
    "fixed": dict(x0=[2.0, 1.0], constraints=[LinearConstraint(matrix, rhs, rhs)],
                  bounds=Bounds([2.0, 0.0], [2.0, np.inf])),
    "inconsistent": dict(x0=[0.0, 0.0], constraints=[LinearConstraint(
        matrix, [3.0, 7.0, 1.0], [3.0, 7.0, 1.0])]),
}

out = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_redundant_reference.py",
    f"! SciPy version: {scipy.__version__}; factorization_method='SVDFactorization'",
    "module test_optimize_trust_constr_redundant_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for name, parameters in scenarios.items():
    result = minimize(objective, method="trust-constr", jac=gradient,
                      hess=hessian,
                      options={"factorization_method": "SVDFactorization",
                               "gtol": 1.0e-8, "xtol": 1.0e-8, "maxiter": 150},
                      **parameters)
    expected_status = 4 if name == "inconsistent" else 1
    if result.status != expected_status:
        raise RuntimeError((name, result.status, result.message))
    vals = ", ".join(f"{v:.17e}_dp" for v in result.x)
    out.extend([
        f"    real(dp), parameter :: {name}_x(2) = [ {vals} ]",
        f"    real(dp), parameter :: {name}_cv = {result.constr_violation:.17e}_dp",
        f"    integer, parameter :: {name}_status = {result.status}",
        f"    integer, parameter :: {name}_nit = {result.nit}",
    ])
    print(f"{name}: x={result.x} status={result.status} "
          f"nit={result.nit} cv={result.constr_violation:.3e}")
out.append("end module test_optimize_trust_constr_redundant_reference")

outfile = Path(__file__).resolve().parent.parent / "test/optimize_trust_constr_redundant_reference.f90"
outfile.write_text("\n".join(out) + "\n", encoding="ascii")
print("Generated:", outfile)
