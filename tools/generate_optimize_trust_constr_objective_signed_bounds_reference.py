"""Regenerate bounded signed objective finite-difference references (SciPy 1.17)."""

from pathlib import Path
import numpy as np
from scipy.optimize import Bounds, LinearConstraint, minimize

CASES = {
    "interior": ([2.0, -3.0], [1.0, -4.0], [3.0, -2.0], [-0.1, 0.2]),
    "lower_first": ([1.0, -3.0], [1.0, -4.0], [3.0, -2.0], [-0.1, 0.2]),
    "lower_second": ([2.0, -4.0], [1.0, -4.0], [3.0, -2.0], [-0.1, 0.2]),
    "positive_rel": ([2.0, -3.0], [1.0, -4.0], [3.0, -2.0], [0.1, 0.2]),
}


def cubic(x):
    return x[0] ** 3 + 2 * x[1] ** 3


lines = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_objective_signed_bounds_reference.py",
    "module test_optimize_trust_constr_objective_signed_bounds_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for name, (x0, lo, hi, rel) in CASES.items():
    probes = []

    def objective(x):
        probes.append(x.copy())
        return cubic(x)

    result = minimize(
        objective,
        x0,
        method="trust-constr",
        jac="2-point",
        bounds=Bounds(lo, hi, keep_feasible=True),
        options={"maxiter": 1, "finite_diff_rel_step": np.asarray(rel)},
    )
    assert result.nfev == len(probes) == 3
    print(name, "gradient:", result.grad, "probes:", probes)
    values = ", ".join(f"{float(v):.17g}_dp" for v in result.grad)
    lines.append(f"    real(dp), parameter :: {name}_grad(2) = [{values}]")
lines += ["end module test_optimize_trust_constr_objective_signed_bounds_reference", ""]
out = Path(__file__).resolve().parents[1] / "test" / "optimize_trust_constr_objective_signed_bounds_reference.f90"
out.write_text("\n".join(lines), encoding="ascii")
print("Wrote", out)
