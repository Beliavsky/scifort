! Reads cases generated by compare_signal_denoise_scipy.py on stdin.
program denoise_reference_driver
    use scifort_kinds, only : dp
    use scifort_signal_denoise, only : medfilt, medfilt2d, wiener
    implicit none

    integer :: nc, ic, mode, dtype, ndim, ks(3), dims(3), noise_flag, n, status
    real(dp) :: noise_power
    real(dp), allocatable :: x(:), y(:)
    integer :: i

    read(*,*) nc
    do ic = 1, nc
        read(*,*) mode, dtype, ndim, noise_flag
        read(*,*) dims(1:ndim)
        read(*,*) ks(1:ndim)
        read(*,*) noise_power
        n = product(dims(1:ndim))
        allocate(x(n), y(n))
        read(*,*) x
        select case (ndim)
        case (1)
            if (dtype == 0) then
                if (mode == 1) then
                    y = real(reshape(medfilt(x, kernel_shape=ks(1:1), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(x, kernel_shape=ks(1:1), status=status), [n])
                else
                    y = reshape(wiener(x, kernel_shape=ks(1:1), noise=noise_power, status=status), [n])
                end if
            else
                if (mode == 1) then
                    y = real(reshape(medfilt(nint(x), kernel_shape=ks(1:1), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(nint(x), kernel_shape=ks(1:1), status=status), [n])
                else
                    y = reshape(wiener(nint(x), kernel_shape=ks(1:1), noise=noise_power, status=status), [n])
                end if
            end if
        case (2)
            if (dtype == 0) then
                if (mode == 1) then
                    y = real(reshape(medfilt(reshape(x, dims(1:2)), kernel_shape=ks(1:2), status=status), [n]), dp)
                else if (mode == 3) then
                    y = real(reshape(medfilt2d(reshape(x, dims(1:2)), kernel_shape=ks(1:2), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(reshape(x, dims(1:2)), kernel_shape=ks(1:2), status=status), [n])
                else
                    y = reshape(wiener(reshape(x, dims(1:2)), kernel_shape=ks(1:2), noise=noise_power, status=status), [n])
                end if
            else
                if (mode == 1) then
                    y = real(reshape(medfilt(reshape(nint(x), dims(1:2)), kernel_shape=ks(1:2), status=status), [n]), dp)
                else if (mode == 3) then
                    y = real(reshape(medfilt2d(reshape(nint(x), dims(1:2)), kernel_shape=ks(1:2), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(reshape(nint(x), dims(1:2)), kernel_shape=ks(1:2), status=status), [n])
                else
                    y = reshape(wiener(reshape(nint(x), dims(1:2)), kernel_shape=ks(1:2), noise=noise_power, status=status), [n])
                end if
            end if
        case (3)
            if (dtype == 0) then
                if (mode == 1) then
                    y = real(reshape(medfilt(reshape(x, dims(1:3)), kernel_shape=ks(1:3), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(reshape(x, dims(1:3)), kernel_shape=ks(1:3), status=status), [n])
                else
                    y = reshape(wiener(reshape(x, dims(1:3)), kernel_shape=ks(1:3), noise=noise_power, status=status), [n])
                end if
            else
                if (mode == 1) then
                    y = real(reshape(medfilt(reshape(nint(x), dims(1:3)), kernel_shape=ks(1:3), status=status), [n]), dp)
                else if (noise_flag == 0) then
                    y = reshape(wiener(reshape(nint(x), dims(1:3)), kernel_shape=ks(1:3), status=status), [n])
                else
                    y = reshape(wiener(reshape(nint(x), dims(1:3)), kernel_shape=ks(1:3), noise=noise_power, status=status), [n])
                end if
            end if
        case default
            error stop 'unsupported rank'
        end select
        write(*, '(i0)', advance='no') status
        do i = 1, n
            write(*, '(1x,es25.16e3)', advance='no') y(i)
        end do
        write(*,*)
        deallocate(x, y)
    end do
end program denoise_reference_driver
