#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for multidimensional root solving."""

from pathlib import Path
import numpy as np
import scipy
from scipy import optimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def emit_vector(parts, name, values):
    values = np.asarray(values, dtype=float).ravel()
    parts.append(f"    real(dp), parameter :: {name}({values.size}) = [ &\n")
    for i, value in enumerate(values):
        suffix = ", &" if i + 1 < values.size else "]"
        parts.append(f"        {fmt(value)}{suffix}\n")


def emit_result(parts, prefix, result):
    emit_vector(parts, f"{prefix}_x_ref", result.x)
    emit_vector(parts, f"{prefix}_fun_ref", result.fun)
    parts.append(f"    integer, parameter :: {prefix}_nfev_ref = {int(result.nfev)}\n")
    parts.append(
        f"    integer, parameter :: {prefix}_njev_ref = {int(getattr(result, 'njev', 0))}\n"
    )
    parts.append(
        f"    integer, parameter :: {prefix}_nit_ref = {int(getattr(result, 'nit', 0))}\n"
    )
    status = getattr(result, "status", 1 if result.success else 2)
    parts.append(f"    integer, parameter :: {prefix}_status_ref = {int(status)}\n")


def system(x):
    return np.array([
        x[0] * np.cos(x[1]) - 4.0,
        x[1] * x[0] - x[1] - 5.0,
    ])


def system_jac(x):
    return np.array([
        [np.cos(x[1]), -x[0] * np.sin(x[1])],
        [x[1], x[0] - 1.0],
    ])


def overdetermined(x):
    return np.array([
        x[0] + x[1] - 3.0,
        2.0 * x[0] - x[1],
        x[0] - 2.0 * x[1] + 1.0,
    ])


def overdetermined_jac(x):
    del x
    return np.array([[1.0, 1.0], [2.0, -1.0], [1.0, -2.0]])



def nonlinear_system(x):
    return np.array([
        x[0] + 0.5 * (x[0] - x[1]) ** 3 - 1.0,
        0.5 * (x[1] - x[0]) ** 3 + x[1],
    ])


def easy_mixing_system(x):
    return np.array([1.0 - x[0], 2.0 - x[1]])


def diagonal(x):
    return np.array([x[0] ** 2 - 2.0, x[1] ** 2 - 3.0])


def krylov_linear_system(x):
    return np.array([
        3.0 * x[0] + x[1] - 1.0,
        x[0] + 2.0 * x[1] - 2.0,
    ])


parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_root_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_root_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]

x0 = np.array([1.0, 1.0])
emit_result(parts, "hybr", optimize.root(system, x0, method="hybr"))
emit_result(parts, "hybr_jac", optimize.root(system, x0, method="hybr", jac=system_jac))
emit_result(parts, "lm", optimize.root(system, x0, method="lm"))
emit_result(parts, "lm_jac", optimize.root(system, x0, method="lm", jac=system_jac))
emit_result(parts, "lm_over", optimize.root(overdetermined, x0, method="lm"))
emit_result(
    parts,
    "lm_over_jac",
    optimize.root(overdetermined, x0, method="lm", jac=overdetermined_jac),
)
emit_result(
    parts,
    "hybr_band",
    optimize.root(diagonal, x0, method="hybr", options={"band": (0, 0)}),
)

x, info, ier, _ = optimize.fsolve(system, x0, full_output=True)
emit_vector(parts, "fsolve_x_ref", x)
emit_vector(parts, "fsolve_fun_ref", info["fvec"])
parts.append(f"    integer, parameter :: fsolve_nfev_ref = {int(info['nfev'])}\n")
parts.append(f"    integer, parameter :: fsolve_status_ref = {int(ier)}\n")


nonlin_x0 = np.array([0.0, 0.0])
for method in ("broyden1", "broyden2", "anderson", "diagbroyden"):
    emit_result(
        parts,
        f"{method}_nonlin",
        optimize.root(nonlinear_system, nonlin_x0, method=method),
    )
for method in ("linearmixing", "excitingmixing"):
    emit_result(
        parts,
        f"{method}_easy",
        optimize.root(easy_mixing_system, nonlin_x0, method=method),
    )
emit_result(
    parts,
    "broyden1_wolfe",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="broyden1",
        options={"line_search": "wolfe"},
    ),
)
for reduction, max_rank in (("restart", 2), ("simple", 2), ("svd", 3)):
    emit_result(
        parts,
        f"broyden1_{reduction}_rank",
        optimize.root(
            nonlinear_system,
            nonlin_x0,
            method="broyden1",
            options={
                "jac_options": {
                    "max_rank": max_rank,
                    "reduction_method": reduction,
                }
            },
        ),
    )
emit_result(
    parts,
    "broyden2_simple_rank",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="broyden2",
        options={
            "jac_options": {"max_rank": 2, "reduction_method": "simple"}
        },
    ),
)
emit_result(
    parts,
    "broyden1_nolinesearch",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="broyden1",
        options={"line_search": None},
    ),
)
emit_result(
    parts,
    "broyden1_tol",
    optimize.root(nonlinear_system, nonlin_x0, method="broyden1", tol=1.0e-10),
)
emit_result(
    parts,
    "broyden1_limit",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="broyden1",
        options={"maxiter": 2},
    ),
)
emit_result(
    parts,
    "dfsane_default",
    optimize.root(nonlinear_system, nonlin_x0, method="df-sane"),
)
emit_result(
    parts,
    "dfsane_cheng",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="df-sane",
        options={"line_search": "cheng"},
    ),
)
emit_result(
    parts,
    "dfsane_tol",
    optimize.root(nonlinear_system, nonlin_x0, method="df-sane", tol=1.0e-12),
)
emit_result(
    parts,
    "dfsane_limit",
    optimize.root(
        nonlinear_system,
        nonlin_x0,
        method="df-sane",
        options={"maxfev": 2},
    ),
)

krylov_linear_x0 = np.array([0.0, 0.0])
emit_result(
    parts,
    "krylov_default",
    optimize.root(krylov_linear_system, krylov_linear_x0, method="krylov"),
)
emit_result(
    parts,
    "krylov_rdiff",
    optimize.root(
        krylov_linear_system,
        krylov_linear_x0,
        method="krylov",
        options={"jac_options": {"rdiff": 1.0e-6}},
    ),
)
emit_result(
    parts,
    "krylov_outer0",
    optimize.root(
        diagonal,
        x0,
        method="krylov",
        options={"jac_options": {"outer_k": 0}},
    ),
)
emit_result(
    parts,
    "krylov_gmres",
    optimize.root(
        diagonal,
        x0,
        method="krylov",
        options={"jac_options": {"method": "gmres"}},
    ),
)
emit_result(
    parts,
    "krylov_wolfe",
    optimize.root(
        diagonal,
        x0,
        method="krylov",
        options={"line_search": "wolfe", "jac_options": {"outer_k": 0}},
    ),
)
emit_result(
    parts,
    "krylov_limit",
    optimize.root(
        diagonal,
        x0,
        method="krylov",
        options={"maxiter": 2, "jac_options": {"outer_k": 0}},
    ),
)
emit_result(
    parts,
    "krylov_fatol",
    optimize.root(
        diagonal,
        x0,
        method="krylov",
        options={"fatol": 1.0e-10, "jac_options": {"outer_k": 0}},
    ),
)

parts.append("end module test_optimize_root_reference\n")
out = Path(__file__).resolve().parents[1] / "test" / "optimize_root_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
