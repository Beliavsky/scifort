#!/usr/bin/env python3
"""Numerically compare mixed-type SciFort 1D convolution with SciPy 1.17.

The reference file is generated by the independent Fortran driver. The input
signals are reconstituted here from the deterministic analytic definitions.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np
from scipy import signal

MODES = ('full', 'same', 'valid')
METHODS = ('direct', 'fft', 'auto')


def run(path: Path) -> None:
    cases = 0
    samples = 0
    worst = 0.0
    with path.open(encoding='utf-8') as stream:
        while header := stream.readline():
            cols = header.split()
            if len(cols) != 8 or cols[0] != 'CASE':
                raise AssertionError(f'Invalid case header: {header!r}')
            family, order, imode, ialg, n, m, count = map(int, cols[1:])
            i = np.arange(1, n+1, dtype=float)
            j = np.arange(1, m+1, dtype=float)
            a = np.sin(0.137*i) + 0.25*np.cos(0.031*i)
            b = np.cos(0.221*j) - 0.17*np.sin(0.052*j)
            za = a + 1j*(0.23*np.cos(0.191*i))
            zb = b + 1j*(0.29*np.sin(0.109*j))
            x, h = (a, zb) if order == 1 else (za, b)
            mode = MODES[imode - 1]
            if family == 1:
                reference = signal.convolve(x,h,mode,method=METHODS[ialg-1])
            elif family == 2:
                reference = signal.correlate(x,h,mode,method=METHODS[ialg-1])
            elif family == 3:
                reference = signal.fftconvolve(x,h,mode)
            elif family == 4:
                reference = signal.oaconvolve(x,h,mode)
            else:
                raise AssertionError(f'Invalid family {family}')
            assert len(reference) == count, (family, order, n, m, count, len(reference))
            actual = np.empty(count,dtype=np.complex128)
            for k in range(count):
                line=stream.readline()
                if not line: raise AssertionError('Truncated reference file')
                real, imag = map(float,line.split())
                actual[k] = complex(real,imag)
            diff = np.max(np.abs(actual-reference))
            scale = max(1.0, float(np.max(np.abs(reference))))
            if diff > 4e-11 * scale:
                raise AssertionError(f'Case {cases}: {family=} {order=} {mode=} {ialg=} '
                                     f'{n=} {m=} error={diff:.5g} scale={scale:.5g}')
            worst = max(worst,float(diff))
            samples += count
            cases += 1
    assert cases == 960, cases
    print(f'PASS: {cases} mixed SciPy 1.17 cases, {samples} complex values, '
          f'max abs error {worst:.3e}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('file',type=Path)
    args = parser.parse_args()
    run(args.file)

if __name__ == '__main__':
    main()
