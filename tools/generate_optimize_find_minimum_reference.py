#!/usr/bin/env python3
"""Generate scalar Chandrupatla-minimization references using SciPy 1.17."""

from pathlib import Path

import math

import numpy as np
import scipy
from scipy.optimize import elementwise


def shifted(x):
    return (x - 1.2) ** 2 + 1.0


def other(x):
    return (x + 1.25) ** 2 + 0.5


def quartic(x):
    return (x + 0.75) ** 4 + 0.2 * (x + 0.75) ** 2 + 0.1


def kink(x):
    return np.abs(x - 1.5) + 0.2


def exponential(x):
    return np.exp(x) - 3 * x


def flat(x):
    return 2.0 + 0.0 * x


def invalid(x):
    return (x - 4) ** 2


cases = [
    ('shifted', shifted, (0., 1., 3.), {}),
    ('reversed', shifted, (3., 1., 0.), {}),
    ('other', other, (-3., -1., 1.), {}),
    ('quartic', quartic, (-2., -1., 1.), {}),
    ('kink', kink, (0., 1., 3.), {}),
    ('exponential', exponential, (0., 1., 3.), {}),
    ('flat', flat, (0., 1., 3.), {}),
    ('invalid', invalid, (0., 1., 2.), {}),
    ('max0', shifted, (0., 1., 3.), {'maxiter': 0}),
    ('max1', shifted, (0., 1., 3.), {'maxiter': 1}),
    ('max2', shifted, (0., 1., 3.), {'maxiter': 2}),
    ('xatol', shifted, (0., 1., 3.), {'tolerances': {'xatol': 0.1}}),
    ('fatol', shifted, (0., 1., 3.), {'tolerances': {'fatol': 0.1}}),
    ('strict', shifted, (0., 1., 3.), {'tolerances': {'xrtol': 1e-12, 'xatol': 0., 'fatol': 0., 'frtol': 0.}}),
    ('sort', other, (1., -3., -1.), {}),
]

lines = [
    '! SPDX-License-Identifier: MIT\n',
    '! Generated by tools/generate_optimize_find_minimum_reference.py\n',
    f'! SciPy version: {scipy.__version__}\n',
    'module test_optimize_find_minimum_reference\n',
    '    use scifort_kinds, only : dp\n',
    '    implicit none\n',
]
for label, fun, init, kw in cases:
    res = elementwise.find_minimum(fun, init, **kw)
    for field, value in zip(('x', 'f_x', 'xl', 'xm', 'xr', 'fl', 'fm', 'fr'),
                            (res.x, res.f_x, *res.bracket, *res.f_bracket)):
        lines.append(f'    real(dp), parameter :: {label}_{field}_ref = {float(value):.17e}_dp\n'
                     if math.isfinite(float(value)) else
                     f'    real(dp), parameter :: {label}_{field}_ref = 0.0_dp ! NaN in SciPy\n')
    for field in ('nit', 'nfev', 'status'):
        lines.append(f'    integer, parameter :: {label}_{field}_ref = {int(getattr(res, field))}\n')
lines.append('end module test_optimize_find_minimum_reference\n')
out = Path(__file__).resolve().parents[1] / 'test' / 'optimize_find_minimum_reference.f90'
out.write_text(''.join(lines), encoding='ascii')
print(f'Wrote {out} with {len(cases)} SciPy {scipy.__version__} cases')
for l,f,i,kw in cases:
    r=elementwise.find_minimum(f,i,**kw)
    print(f'{l:12s} {int(r.status):3d} {int(r.nit):3d} {int(r.nfev):3d} {float(r.x):20.13g} {tuple(float(x) for x in r.bracket)}')
