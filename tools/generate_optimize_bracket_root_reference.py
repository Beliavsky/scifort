#!/usr/bin/env python3
"""Generate scalar bracket_root reference cases from SciPy 1.17."""

from pathlib import Path

import scipy
from scipy.optimize import elementwise


def cubic(x):
    return x**3 - 2*x - 5


def right(x):
    return x - 8


def left(x):
    return x + 3


def initial(x):
    return x - 0.5


def zero_left(x):
    return x


def zero_right(x):
    return x - 1


def two(x):
    return x - 2


cases = [
    ("cubic", cubic, 0.0, {}),
    ("right", right, 0.0, {}),
    ("left", left, 0.0, {}),
    ("bounded_right", right, 0.0, {"xmax": 10.0}),
    ("bounded_left", left, 0.0, {"xmin": -5.0}),
    ("factor3", right, 0.0, {"factor": 3.0}),
    ("initial", initial, 0.0, {}),
    ("zero_left", zero_left, 0.0, {}),
    ("zero_right", zero_right, 0.0, {}),
    ("shortcap", right, 0.0, {"maxiter": 1}),
    ("boundcap", right, 0.2, {"xr0": 0.8, "xmin": 0.0, "xmax": 1.0, "maxiter": 4}),
    ("leftclamped", two, 0.0, {"xmin": 0.0}),
    ("onlyright", right, 0.0, {"xmin": 0.0}),
    ("rightlimited_default", left, 0.0, {"xmax": 1.0}),
]

lines = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_bracket_root_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_bracket_root_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]
for label, fun, start, opts in cases:
    res = elementwise.bracket_root(fun, start, **opts)
    for name, value in zip(("xl", "xr", "fl", "fr"), (*res.bracket, *res.f_bracket)):
        lines.append(f"    real(dp), parameter :: {label}_{name}_ref = {float(value):.17e}_dp\n")
    lines.append(f"    integer, parameter :: {label}_nit_ref = {int(res.nit)}\n")
    lines.append(f"    integer, parameter :: {label}_nfev_ref = {int(res.nfev)}\n")
    lines.append(f"    integer, parameter :: {label}_status_ref = {int(res.status)}\n")
lines.append("end module test_optimize_bracket_root_reference\n")
out = Path(__file__).resolve().parents[1] / "test" / "optimize_bracket_root_reference.f90"
out.write_text("".join(lines), encoding="ascii")
print(f"Wrote {out} with {len(cases)} SciPy {scipy.__version__} cases")
