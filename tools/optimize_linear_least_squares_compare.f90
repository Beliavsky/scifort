! Reference comparison driver: input and output are generated by the Python
! companion script. It is a standalone program, not intended for fpm test.
program optimize_linear_least_squares_compare
    use scifort_kinds, only : dp
    use scifort_optimize_linear_least_squares, only : nnls, lsq_linear, linear_lsq_result
    implicit none
    real(dp), allocatable :: a(:,:), b(:), lo(:), hi(:), x(:)
    real(dp) :: rnorm
    type(linear_lsq_result) :: res
    integer :: nc, test, m, n, i, mode, status, j

    read(*,*) nc
    do test=1,nc
        read(*,*) mode,m,n
        allocate(a(m,n),b(m),lo(n),hi(n),x(n))
        do i=1,m
            read(*,*) a(i,:)
        end do
        read(*,*) b
        read(*,*) lo
        read(*,*) hi
        if (mode == 1) then
            call nnls(a,b,x,rnorm,status)
            write(*,'(i0,1x,i0,1x,es24.15)') test,status,0.5_dp*rnorm**2
        else
            res=lsq_linear(a,b,lo,hi,method='bvls')
            status=res%status
            if (allocated(res%x)) x=res%x
            write(*,'(i0,1x,i0,1x,es24.15)') test,status,res%cost
        end if
        do j=1,n
            write(*,'(es24.15,1x)',advance='no') x(j)
        end do
        write(*,*)
        deallocate(a,b,lo,hi,x)
    end do
end program optimize_linear_least_squares_compare
