#!/usr/bin/env python3
"""Generate SciPy 1.17 references for make_distribution/truncate."""

from pathlib import Path
import numpy as np
import scipy
from scipy import stats


def fmt(v):
    v = float(v)
    if np.isnan(v):
        return "quiet_nan(0.0_dp)"
    if np.isposinf(v):
        return "positive_infinity(0.0_dp)"
    if np.isneginf(v):
        return "negative_infinity(0.0_dp)"
    return f"{v:.17e}_dp"


def rvec(name, values):
    a = np.asarray(values, dtype=float).reshape(-1)
    lines = [f"    real(dp), parameter :: {name}({a.size}) = [ &\n"]
    for i, v in enumerate(a):
        suffix = ", &" if i < a.size - 1 else " ]"
        lines.append(f"        {fmt(v)}{suffix}\n")
    return "".join(lines)


x = np.array([-2.0, -1.0, -0.5, 0.0, 1.5, 2.0, 3.0])
p = np.array([0.0, 0.1, 0.5, 0.9, 1.0])

normal = stats.Normal()
tn = stats.truncate(normal, lb=-1.0, ub=2.0)
shifted = stats.truncate(stats.Normal(mu=1.0, sigma=2.0), lb=-2.0, ub=2.0)

Rayleigh = stats.make_distribution(stats.rayleigh)
ray = stats.truncate(Rayleigh(), lb=0.5, ub=3.0)
ray_x = np.array([0.5, 0.75, 1.0, 2.0, 3.0])
ray_p = np.array([0.05, 0.5, 0.95])

Uniform = stats.make_distribution(stats.uniform)
uniform = stats.truncate(Uniform(), lb=-2.0, ub=0.8)
uniform_x = np.array([0.0, 0.4, 0.8])

parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_distribution_infrastructure_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_distribution_infrastructure_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
    rvec("truncate_x_ref", x),
    rvec("truncate_p_ref", p),
    rvec("truncate_normal_pdf_ref", tn.pdf(x)),
    rvec("truncate_normal_logpdf_ref", tn.logpdf(x[2:5])),
    rvec("truncate_normal_cdf_ref", tn.cdf(x)),
    rvec("truncate_normal_logcdf_ref", tn.logcdf(x[2:5])),
    rvec("truncate_normal_sf_ref", tn.ccdf(x)),
    rvec("truncate_normal_logsf_ref", tn.logccdf(x[2:5])),
    rvec("truncate_normal_ppf_ref", tn.icdf(p)),
    rvec("truncate_normal_isf_ref", tn.iccdf(p)),
    rvec("truncate_shifted_pdf_ref", shifted.pdf(x)),
    rvec("truncate_shifted_cdf_ref", shifted.cdf(x)),
    rvec("truncate_shifted_ppf_ref", shifted.icdf(p)),
    rvec("truncate_rayleigh_x_ref", ray_x),
    rvec("truncate_rayleigh_p_ref", ray_p),
    rvec("truncate_rayleigh_pdf_ref", ray.pdf(ray_x)),
    rvec("truncate_rayleigh_cdf_ref", ray.cdf(ray_x)),
    rvec("truncate_rayleigh_ppf_ref", ray.icdf(ray_p)),
    rvec("truncate_uniform_x_ref", uniform_x),
    rvec("truncate_uniform_pdf_ref", uniform.pdf(uniform_x)),
    rvec("truncate_uniform_cdf_ref", uniform.cdf(uniform_x)),
    "end module test_distribution_infrastructure_reference\n",
]

out = Path(__file__).resolve().parents[1] / "test" / "test_distribution_infrastructure_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
