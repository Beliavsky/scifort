#!/usr/bin/env python3
"""Generate SciPy 1.17 numerical-gradient reference values for trust-constr."""
from pathlib import Path
import numpy as np
import scipy
from scipy.optimize._numdiff import approx_derivative


def cubic(x):
    return x[0]**3 + 2 * x[1]**3


x0 = np.array([2.0, -3.0])
steps = np.array([0.1, 0.2])
outputs = {
    'three_point': approx_derivative(cubic, x0, method='3-point', rel_step=steps),
    'two_point': approx_derivative(cubic, x0, method='2-point', rel_step=steps),
    'signed_two_point': approx_derivative(cubic, x0, method='2-point', rel_step=[-0.1, 0.2]),
    'lower_bound': approx_derivative(cubic, x0, method='3-point', rel_step=steps,
                                      bounds=(np.array([2.0, -np.inf]), np.full(2, np.inf))),
    'zero_coordinate': approx_derivative(cubic, np.array([0.0, -3.0]), method='3-point',
                                         rel_step=steps),
}
lines = [
    '! SPDX-License-Identifier: MIT',
    '! Generated by tools/generate_optimize_trust_constr_objective_rel_step_reference.py',
    f'! SciPy version: {scipy.__version__}',
    'module test_optimize_trust_constr_objective_rel_step_reference',
    '    use scifort_kinds, only : dp',
    '    implicit none',
]
for name, gradient in outputs.items():
    lines.append(f'    real(dp), parameter :: {name}(2) = [ &')
    lines.append(f'        {gradient[0]:.17e}_dp, {gradient[1]:.17e}_dp ]')
lines.append('end module test_optimize_trust_constr_objective_rel_step_reference')
target = Path(__file__).resolve().parent.parent / 'test/optimize_trust_constr_objective_rel_step_reference.f90'
target.write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'SciPy {scipy.__version__}: generated {target}')
for name, x in outputs.items():
    print(name, x.tolist())
