#!/usr/bin/env python3
"""Generate SciPy 1.17 scalar bracketing reference values for Fortran tests."""

from pathlib import Path

import scipy
from scipy.optimize import bracket


def quadratic(x):
    return (x - 2.0) ** 2


def far_quadratic(x):
    return (x - 50.0) ** 2


def polynomial(x):
    return (x - 2.0) * x * (x + 2.0) ** 2


cases = [
    ("default", quadratic, {}),
    ("reverse", quadratic, {"xa": 3.0, "xb": 4.0}),
    ("uphill", quadratic, {"xa": -2.0, "xb": -1.0}),
    ("polynomial", polynomial, {}),
    ("far_default", far_quadratic, {}),
    ("far_limited", far_quadratic, {"grow_limit": 2.0}),
]

parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_bracket_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_bracket_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]
for name, fun, kwargs in cases:
    result = bracket(fun, **kwargs)
    for label, value in zip(("xa", "xb", "xc", "fa", "fb", "fc"), result[:6]):
        parts.append(f"    real(dp), parameter :: {name}_{label}_ref = {float(value):.17e}_dp\n")
    parts.append(f"    integer, parameter :: {name}_calls_ref = {int(result[6])}\n")
parts.append("end module test_optimize_bracket_reference\n")

path = Path(__file__).resolve().parents[1] / "test" / "optimize_bracket_reference.f90"
path.write_text("".join(parts), encoding="ascii")
print(path)
