#!/usr/bin/env python3
"""Generate SciPy 1.17 references for bounded/constrained minimization."""

from pathlib import Path

import numpy as np
import scipy
from scipy import optimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def emit_vector(parts, name, values):
    values = np.asarray(values, dtype=float).ravel()
    parts.append(f"    real(dp), parameter :: {name}({values.size}) = [ &\n")
    for i, value in enumerate(values):
        suffix = ", &" if i + 1 < values.size else "]"
        parts.append(f"        {fmt(value)}{suffix}\n")


def emit_result(parts, prefix, result):
    emit_vector(parts, f"{prefix}_x_ref", result.x)
    parts.append(f"    real(dp), parameter :: {prefix}_fun_ref = {fmt(result.fun)}\n")
    parts.append(f"    integer, parameter :: {prefix}_nit_ref = {int(result.nit)}\n")
    parts.append(f"    integer, parameter :: {prefix}_nfev_ref = {int(result.nfev)}\n")
    parts.append(
        f"    integer, parameter :: {prefix}_njev_ref = "
        f"{int(getattr(result, 'njev', 0))}\n"
    )
    parts.append(f"    integer, parameter :: {prefix}_status_ref = {int(result.status)}\n")


def bounded_quadratic(x):
    return (x[0] - 2.0) ** 2 + (x[1] + 1.0) ** 2


def bounded_quadratic_grad(x):
    return np.array([2.0 * (x[0] - 2.0), 2.0 * (x[1] + 1.0)])


def rosenbrock(x):
    return 100.0 * (x[1] - x[0] ** 2) ** 2 + (1.0 - x[0]) ** 2


def rosenbrock_grad(x):
    g1 = 200.0 * (x[1] - x[0] ** 2)
    return np.array([-2.0 * (x[0] * (g1 - 1.0) + 1.0), g1])


def slsqp_eq_fun(x):
    return (x[0] - 1.0) ** 2 + (x[1] - 2.5) ** 2


def slsqp_eq_grad(x):
    return np.array([2.0 * (x[0] - 1.0), 2.0 * (x[1] - 2.5)])


def eq_constraint(x):
    return np.array([x[0] + x[1] - 2.0])


def eq_constraint_jac(x):
    del x
    return np.array([[1.0, 1.0]])


def norm2(x):
    return x @ x


def norm2_grad(x):
    return 2.0 * x


def ineq_constraint(x):
    return np.array([x[0] + x[1] - 1.0])


def ineq_constraint_jac(x):
    del x
    return np.array([[1.0, 1.0]])


parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_minimize_constrained_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_minimize_constrained_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]

bounds = optimize.Bounds([-1.0, -2.0], [1.0, 0.0])
x0 = np.array([0.0, 0.0])
emit_result(
    parts,
    "lbfgsb_jac",
    optimize.minimize(
        bounded_quadratic, x0, method="L-BFGS-B", jac=bounded_quadratic_grad,
        bounds=bounds,
    ),
)
emit_result(
    parts,
    "lbfgsb_fd",
    optimize.minimize(bounded_quadratic, x0, method="L-BFGS-B", bounds=bounds),
)
emit_result(
    parts,
    "lbfgsb_limit",
    optimize.minimize(
        bounded_quadratic, x0, method="L-BFGS-B", jac=bounded_quadratic_grad,
        bounds=bounds, options={"maxiter": 1},
    ),
)
emit_result(
    parts,
    "lbfgsb_default",
    optimize.minimize(
        bounded_quadratic, x0, jac=bounded_quadratic_grad, bounds=bounds,
    ),
)

emit_result(
    parts,
    "tnc_jac",
    optimize.minimize(
        bounded_quadratic, x0, method="TNC", jac=bounded_quadratic_grad,
        bounds=bounds,
    ),
)
emit_result(
    parts,
    "tnc_fd",
    optimize.minimize(bounded_quadratic, x0, method="TNC", bounds=bounds),
)
rosen_x0 = np.array([-2.0, 1.0])
emit_result(
    parts,
    "tnc_rosen",
    optimize.minimize(
        rosenbrock, rosen_x0, method="TNC", jac=rosenbrock_grad,
        bounds=optimize.Bounds([-np.inf, -1.5], [np.inf, np.inf]),
        options={"maxfun": 200},
    ),
)
emit_result(
    parts,
    "tnc_active",
    optimize.minimize(
        rosenbrock, rosen_x0, method="TNC", jac=rosenbrock_grad,
        bounds=optimize.Bounds([-np.inf, 1.5], [np.inf, np.inf]),
        options={"maxfun": 200},
    ),
)
emit_result(
    parts,
    "tnc_mixed_fixed",
    optimize.minimize(
        bounded_quadratic, x0, method="TNC", jac=bounded_quadratic_grad,
        bounds=optimize.Bounds([1.0, -2.0], [1.0, 0.0]),
    ),
)

lower_only = optimize.Bounds([0.0, 0.0], [np.inf, np.inf])
eq_analytic = {"type": "eq", "fun": eq_constraint, "jac": eq_constraint_jac}
eq_numeric = {"type": "eq", "fun": eq_constraint}
xeq = np.array([0.5, 1.5])
emit_result(
    parts,
    "slsqp_eq_jac",
    optimize.minimize(
        slsqp_eq_fun, xeq, method="SLSQP", jac=slsqp_eq_grad,
        bounds=lower_only, constraints=eq_analytic,
    ),
)
emit_result(
    parts,
    "slsqp_eq_fd",
    optimize.minimize(
        slsqp_eq_fun, xeq, method="SLSQP", bounds=lower_only,
        constraints=eq_numeric,
    ),
)
emit_result(
    parts,
    "slsqp_eq_mixed",
    optimize.minimize(
        slsqp_eq_fun, xeq, method="SLSQP", jac=slsqp_eq_grad,
        bounds=lower_only, constraints=eq_numeric,
    ),
)
emit_result(
    parts,
    "slsqp_limit",
    optimize.minimize(
        slsqp_eq_fun, xeq, method="SLSQP", jac=slsqp_eq_grad,
        bounds=lower_only, constraints=eq_analytic, options={"maxiter": 1},
    ),
)

ineq_analytic = {
    "type": "ineq", "fun": ineq_constraint, "jac": ineq_constraint_jac,
}
emit_result(
    parts,
    "slsqp_ineq",
    optimize.minimize(
        norm2, np.array([0.2, 0.2]), method="SLSQP", jac=norm2_grad,
        bounds=lower_only, constraints=ineq_analytic,
    ),
)

parts.append("end module test_optimize_minimize_constrained_reference\n")
out = (
    Path(__file__).resolve().parents[1]
    / "test"
    / "optimize_minimize_constrained_reference.f90"
)
out.write_text("".join(parts), encoding="ascii")
print(out)
