"""Generate SciPy 1.17 trust-constr finite-difference objective Hessian references."""

from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import Bounds, NonlinearConstraint, minimize


def rosen(x):
    return (1.0 - x[0]) ** 2 + 100.0 * (x[1] - x[0] ** 2) ** 2


def rosen_grad(x):
    return np.array([
        2.0 * (x[0] - 1.0) - 400.0 * x[0] * (x[1] - x[0] ** 2),
        200.0 * (x[1] - x[0] ** 2),
    ])


def quadratic(x):
    return (x[0] - 1.0) ** 2 + 3.0 * (x[1] + 2.0) ** 2


def quadratic_grad(x):
    return np.array([2.0 * (x[0] - 1.0), 6.0 * (x[1] + 2.0)])


def circle(x):
    return np.array([np.dot(x, x)])


def circle_jac(x):
    return 2.0 * x[None, :]


def circle_hess(x, multipliers):
    return 2.0 * multipliers[0] * np.eye(2)


def emit_vector(label, vector):
    a, b = (float(v) for v in vector)
    return f"    real(dp), parameter :: {label}(2) = [{a:.17e}_dp, {b:.17e}_dp]"


def main():
    if scipy.__version__ != "1.17.0":
        raise RuntimeError("References pinned to SciPy 1.17.0")
    circle_constraint = NonlinearConstraint(
        circle, np.array([1.0]), np.array([1.0]), jac=circle_jac, hess=circle_hess
    )
    cases = {}
    for scheme in ("2-point", "3-point"):
        prefix = "fd2" if scheme == "2-point" else "fd3"
        cases[prefix + "_rosen"] = minimize(
            rosen, [-1.2, 1.0], method="trust-constr", jac=rosen_grad,
            hess=scheme, options={"maxiter": 200},
        )
        cases[prefix + "_circle"] = minimize(
            quadratic, [0.8, 0.6], method="trust-constr", jac=quadratic_grad,
            hess=scheme, constraints=[circle_constraint], options={"maxiter": 150},
        )
        cases[prefix + "_bounds"] = minimize(
            quadratic, [0.5, 0.3], method="trust-constr", jac=quadratic_grad,
            hess=scheme, bounds=Bounds([0.0, 0.0], [2.0, 3.0]),
            options={"maxiter": 150},
        )
    lines = [
        "! SPDX-License-Identifier: MIT",
        "! Generated by tools/generate_optimize_trust_constr_hess_fd_reference.py",
        f"! SciPy version: {scipy.__version__}",
        "module test_optimize_trust_constr_hess_fd_reference",
        "    use scifort_kinds, only : dp",
        "    implicit none",
    ]
    for label, result in cases.items():
        if not result.success:
            raise RuntimeError(f"Reference {label} did not converge: {result.message}")
        lines.append(emit_vector(label, result.x))
        lines.append(f"    integer, parameter :: {label}_nit = {result.nit}")
    lines.append("end module test_optimize_trust_constr_hess_fd_reference")
    output = Path(__file__).resolve().parents[1] / "test" / "optimize_trust_constr_hess_fd_reference.f90"
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"SciPy {scipy.__version__}: wrote {output.name}")
    for label, result in cases.items():
        print(label, "nit", result.nit, "x", result.x, "njev", result.njev, "nhev", result.nhev)


if __name__ == "__main__":
    main()
