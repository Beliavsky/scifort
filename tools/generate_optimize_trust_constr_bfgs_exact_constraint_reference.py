#!/usr/bin/env python3
"""Generate SciPy references for exact constraints and BFGS objective curvature."""

from pathlib import Path
import numpy as np
import scipy
from scipy.optimize import Bounds, NonlinearConstraint, minimize


def objective_2d(x):
    return np.sum((x - 1.2) ** 2)


def gradient_2d(x):
    return 2 * (x - 1.2)


def circle(x):
    return np.array([np.sum(x ** 2)])


def circle_jac(x):
    return 2 * x[np.newaxis, :]


def circle_hess(x, v):
    return np.diag(np.repeat(2 * v[0], x.size))


def objective_3d(x):
    return (x[0] - 1.3) ** 2 + 2 * (x[1] + 0.8) ** 2 + 0.7 * (x[2] - 1.5) ** 2


def gradient_3d(x):
    return np.array([2 * (x[0] - 1.3), 4 * (x[1] + 0.8), 1.4 * (x[2] - 1.5)])


def first_value(x):
    return np.array([x[0] ** 2 + x[1] - 1.2])


def first_jac(x):
    return np.array([[2 * x[0], 1, 0]])


def first_hess(x, v):
    return np.diag([2 * v[0], 0, 0])


def second_value(x):
    return np.array([x[1] ** 2 + x[2] - 0.7])


def second_jac(x):
    return np.array([[0, 2 * x[1], 1]])


circle_eq = NonlinearConstraint(circle, 1, 1, jac=circle_jac, hess=circle_hess)
circle_upper = NonlinearConstraint(circle, -np.inf, 1, jac=circle_jac, hess=circle_hess)
scenarios = {
    "equality": dict(fun=objective_2d, x0=np.array([0.2, 0.2]),
                     jac=gradient_2d, constraints=[circle_eq]),
    "objective_fd": dict(fun=objective_2d, x0=np.array([0.2, 0.2]),
                         jac="3-point", constraints=[circle_eq]),
    "upper": dict(fun=objective_2d, x0=np.array([0.2, 0.2]),
                  jac=gradient_2d, constraints=[circle_upper]),
    "bounds": dict(fun=objective_2d, x0=np.array([0.2, 0.2]),
                   jac=gradient_2d, constraints=[circle_upper],
                   bounds=Bounds([0, 0], [np.inf, np.inf])),
    "mixed": dict(fun=objective_3d, x0=np.array([1., -0.3, 1.]),
                  jac=gradient_3d, constraints=[
                      NonlinearConstraint(first_value, 0, 0, jac=first_jac, hess=first_hess),
                      NonlinearConstraint(second_value, 0, 0, jac=second_jac)]),
}

lines = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_bfgs_exact_constraint_reference.py",
    f"! SciPy version: {scipy.__version__}",
    "module test_optimize_trust_constr_bfgs_exact_constraint_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for name, args in scenarios.items():
    res = minimize(method="trust-constr", options={"gtol": 1e-10, "maxiter": 500}, **args)
    assert res.success, (name, res.message)
    n = len(res.x)
    entries = ", ".join(f"{v:.17e}_dp" for v in res.x)
    lines.append(f"    real(dp), parameter :: {name}_x({n}) = [ &")
    lines.append(f"        {entries} ]")
    lines.append(f"    real(dp), parameter :: {name}_fun = {res.fun:.17e}_dp")
    print(name, 'x=', res.x, 'fun=', res.fun, 'nit=', res.nit,
          'constr_nhev=', res.constr_nhev)
lines.append("end module test_optimize_trust_constr_bfgs_exact_constraint_reference")
target = Path(__file__).resolve().parent.parent / "test/optimize_trust_constr_bfgs_exact_constraint_reference.f90"
target.write_text("\n".join(lines) + "\n", encoding="ascii")
print("Generated:", target)
