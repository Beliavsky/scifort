#!/usr/bin/env python3
"""Generate SciPy 1.17 reference data for vectorized minimum refinement."""
from pathlib import Path
import numpy as np
from scipy.optimize import elementwise

brackets = np.array(
    [[0.0, -1.0, -4.0, 6.0, 3.0],
     [1.0, 2.0, 1.0, 4.0, 1.0],
     [3.0, 6.0, 4.0, 3.0, 0.0]], dtype=float,
)
result = elementwise.find_minimum(
    lambda x: (x - 1.5)**2 + 0.02*(x - 1.5)**4,
    brackets,
    tolerances={"xatol": 1.0e-12},
)

def array_line(name: str, values: np.ndarray) -> str:
    entries = ", ".join(str(int(v)) for v in values)
    return f"    integer, parameter :: {name}(5) = [{entries}]"

content = "\n".join([
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_elementwise_vectorized_minimum_reference.py",
    "! Reference: SciPy 1.17.0 scipy.optimize.elementwise.find_minimum",
    "module optimize_elementwise_vectorized_minimum_reference",
    "    implicit none",
    "    private",
    "    public :: vector_min_ref_status, vector_min_ref_nit, vector_min_ref_nfev",
    array_line("vector_min_ref_status", result.status),
    array_line("vector_min_ref_nit", result.nit),
    array_line("vector_min_ref_nfev", result.nfev),
    "end module optimize_elementwise_vectorized_minimum_reference",
    "",
])
output = Path(__file__).resolve().parents[1] / "test" / "optimize_elementwise_vectorized_minimum_reference.f90"
output.write_text(content)
print(f"Wrote {output}")
