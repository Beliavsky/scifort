#!/usr/bin/env python3
"""Generate trust-constr references for multiplier-weighted Hessian operators."""
from pathlib import Path
import numpy as np
import scipy
from scipy.optimize import NonlinearConstraint, minimize
from scipy.sparse.linalg import LinearOperator


def objective(x):
    return (x[0] - 1.0) ** 2 + 2.0 * (x[1] + 2.0) ** 2


def gradient(x):
    return np.array([2.0 * (x[0] - 1.0), 4.0 * (x[1] + 2.0)])


def objective_hessian(x):
    return np.diag([2.0, 4.0])


def values(x):
    return np.array([x[0] ** 3 + x[0] * x[1] + x[1]])


def jacobian(x):
    return np.array([[3.0 * x[0] ** 2 + x[1], x[0] + 1.0]])


def full_constraint_hessian(x, v):
    return v[0] * np.array([[6.0 * x[0], 1.0], [1.0, 0.0]])


def constraint_operator(x, v):
    """Equivalent to SciFort's block hessp(x, v, p, hp) interface."""
    matrix = full_constraint_hessian(x, v)
    return LinearOperator((2, 2), matvec=lambda p: matrix @ p,
                          rmatvec=lambda p: matrix.T @ p, dtype=float)


output = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_constraint_hessp_reference.py",
    f"! SciPy version: {scipy.__version__}",
    "module test_optimize_trust_constr_constraint_hessp_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for key, (low, high) in {
    "equality": (0.0, 0.0),
    "inequality": (-0.1, 0.6),
}.items():
    kwargs = {"constraints": [NonlinearConstraint(values, low, high,
                           jac=jacobian, hess=constraint_operator)]}
    result = minimize(objective, np.array([0.6, -1.4]), method="trust-constr",
                      jac=gradient, hess=objective_hessian, **kwargs)
    dense_result = minimize(objective, np.array([0.6, -1.4]), method="trust-constr",
                            jac=gradient, hess=objective_hessian,
                            constraints=[NonlinearConstraint(values, low, high,
                                                              jac=jacobian, hess=full_constraint_hessian)])
    assert result.success and dense_result.success
    assert np.allclose(result.x, dense_result.x, atol=1e-9)
    assert result.nit == dense_result.nit
    assert result.constr_nhev == dense_result.constr_nhev
    output.extend([
        f"    real(dp), parameter :: {key}_x(2) = [ &",
        f"        {result.x[0]:.17e}_dp, {result.x[1]:.17e}_dp ]",
        f"    integer, parameter :: {key}_nit = {result.nit}",
        f"    integer, parameter :: {key}_nfev = {result.nfev}",
        f"    integer, parameter :: {key}_njev = {result.njev}",
        f"    integer, parameter :: {key}_nhev = {result.nhev}",
        f"    integer, parameter :: {key}_constr_nhev = {result.constr_nhev[0]}",
    ])
    print(key, result.x, result.nit, result.nfev, result.njev, result.nhev,
          result.constr_nhev)
output.append("end module test_optimize_trust_constr_constraint_hessp_reference")
path = Path(__file__).resolve().parent.parent / "test/optimize_trust_constr_constraint_hessp_reference.f90"
path.write_text("\n".join(output) + "\n", encoding="ascii")
print("Generated:", path)
