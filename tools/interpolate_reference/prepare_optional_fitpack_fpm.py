#!/usr/bin/env python3
"""Configure the optional SciFort FITPACK subproject to use a supplied local ZIP.

No network access, manual manifest editing, or FITPACK vendoring in SciFort is
needed. This temporarily modifies optional/fitpack_backend/fpm.toml inside the
caller's checkout. Run --restore to reinstate the original pinned manifest.

Usage:
  python tools/interpolate_reference/prepare_optional_fitpack_fpm.py fitpack-main.zip
  cd optional/fitpack_backend && fpm test --compiler gfortran
  python tools/interpolate_reference/prepare_optional_fitpack_fpm.py --restore
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import shutil
import tomllib
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / 'optional' / 'fitpack_backend'
MANIFEST = BACKEND / 'fpm.toml'
BACKUP = BACKEND / 'fpm.toml.before_local_fitpack'
DEST = BACKEND / '.fitpack_local'


def configure(zip_path: Path) -> None:
    if not zip_path.is_file():
        raise FileNotFoundError(zip_path)
    if BACKUP.exists():
        raise RuntimeError('A local FITPACK manifest is already active; use --restore first')
    if DEST.exists():
        raise RuntimeError(f'Local dependency directory already exists: {DEST}')
    with ZipFile(zip_path) as archive:
        members = archive.infolist()
        for member in members:
            path = Path(member.filename)
            if path.is_absolute() or '..' in path.parts:
                raise ValueError('Unsafe ZIP path')
            if (member.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError('ZIP symlinks are not supported')
        manifests = [m.filename for m in members if m.filename.endswith('/fpm.toml')
                     and len(Path(m.filename).parts) == 2]
        if len(manifests) != 1:
            raise ValueError('Expected exactly one top-level FITPACK fpm.toml')
        package = Path(manifests[0]).parts[0]
        payload = tomllib.loads(archive.read(manifests[0]).decode('utf-8'))
        if payload.get('name') != 'fitpack' or not str(payload.get('version', '')).startswith('2.'):
            raise ValueError('This adapter is verified against supplied FITPACK 2.x source')
        if not any(m.filename == f'{package}/src/fitpack_core.F90' for m in members):
            raise ValueError('Expected fitpack_core.F90 source')
        old_manifest = MANIFEST.read_text()
        new_manifest, count = re.subn(
            r'^fitpack\s*=\s*\{[^\n]+\}\s*$',
            f'fitpack = {{ path = ".fitpack_local/{package}" }}', old_manifest,
            count=1, flags=re.MULTILINE)
        if count != 1:
            raise RuntimeError('Unable to locate the FPM FITPACK dependency line')
        candidate = tomllib.loads(new_manifest)
        assert candidate['dependencies']['fitpack']['path'] == f'.fitpack_local/{package}'
        try:
            DEST.mkdir()
            archive.extractall(DEST)
            BACKUP.write_text(old_manifest)
            MANIFEST.write_text(new_manifest)
        except Exception:
            if BACKUP.exists():
                MANIFEST.write_text(BACKUP.read_text())
                BACKUP.unlink()
            shutil.rmtree(DEST, ignore_errors=True)
            raise
    print(f'Configured local FITPACK {payload["version"]}: {DEST / package}')
    print('Run: cd optional/fitpack_backend && fpm test --compiler gfortran')


def restore() -> None:
    if not BACKUP.is_file():
        raise RuntimeError('No saved manifest to restore')
    MANIFEST.write_text(BACKUP.read_text())
    BACKUP.unlink()
    # The extracted files are generated by this helper; do not delete any
    # other directory or any copy of FITPACK outside the generated directory.
    shutil.rmtree(DEST)
    print('Restored the original FPM dependency manifest')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('fitpack', type=Path, nargs='?')
    parser.add_argument('--restore', action='store_true')
    args = parser.parse_args()
    if args.restore:
        restore()
    elif args.fitpack:
        configure(args.fitpack.resolve())
    else:
        parser.error('Provide a FITPACK ZIP path or --restore')


if __name__ == '__main__':
    main()
