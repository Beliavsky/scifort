#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for ``scipy.differentiate``."""

from pathlib import Path
import numpy as np
import scipy
from scipy.differentiate import derivative, jacobian, hessian
from scipy.optimize import rosen


def fmt(value):
    value = float(value)
    if np.isnan(value):
        return "quiet_nan(0.0_dp)"
    if np.isposinf(value):
        return "positive_infinity(0.0_dp)"
    if np.isneginf(value):
        return "negative_infinity(0.0_dp)"
    return f"{value:.17e}_dp"


def rscalar(name, value):
    return f"    real(dp), parameter :: {name} = {fmt(value)}\n"


def iscalar(name, value):
    return f"    integer, parameter :: {name} = {int(value)}\n"


def rvec(name, values):
    a = np.asarray(values, dtype=float).reshape(-1)
    lines = [f"    real(dp), parameter :: {name}({a.size}) = [ &\n"]
    for i, value in enumerate(a):
        suffix = ", &" if i < a.size - 1 else " ]"
        lines.append(f"        {fmt(value)}{suffix}\n")
    return "".join(lines)


def rmat(name, values):
    a = np.asarray(values, dtype=float)
    flat = a.reshape(-1, order="F")
    lines = [f"    real(dp), parameter :: {name}({a.shape[0]}, {a.shape[1]}) = reshape([ &\n"]
    for i, value in enumerate(flat):
        suffix = ", &" if i < flat.size - 1 else " ], &\n"
        lines.append(f"        {fmt(value)}{suffix}\n")
    lines.append(f"        [{a.shape[0]}, {a.shape[1]}])\n")
    return "".join(lines)


cases = {
    "exp_default": derivative(np.exp, 1.0),
    "exp_order4": derivative(np.exp, 1.0, order=4),
    "exp_right": derivative(np.exp, 1.0, step_direction=1),
    "exp_left": derivative(np.exp, 1.0, step_direction=-1),
    "exp_one_iteration": derivative(np.exp, 1.0, maxiter=1),
}

x_array = np.array([-1.0, 0.0, 1.0])
array_case = derivative(np.exp, x_array)


def vector_function(x):
    return np.array([
        x[0],
        5.0 * x[2],
        4.0 * x[1] ** 2 - 2.0 * x[2],
        x[2] * np.sin(x[0]),
    ])


jac_case = jacobian(vector_function, np.array([0.2, 0.3, 0.4]))
rosen_x = np.array([0.5, 0.5, 0.5])
rosen_jac = jacobian(rosen, rosen_x)
rosen_hess = hessian(rosen, rosen_x)

parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_differentiate_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_differentiate_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]

for name, result in cases.items():
    parts.extend([
        rscalar(f"{name}_df_ref", result.df),
        *( [rscalar(f"{name}_error_ref", result.error)] if np.isfinite(result.error) else [] ),
        iscalar(f"{name}_status_ref", result.status),
        iscalar(f"{name}_nit_ref", result.nit),
        iscalar(f"{name}_nfev_ref", result.nfev),
    ])

parts.extend([
    rvec("exp_array_x_ref", x_array),
    rvec("exp_array_df_ref", array_case.df),
    rmat("vector_jacobian_ref", jac_case.df),
    rvec("rosen_gradient_ref", rosen_jac.df),
    rmat("rosen_hessian_ref", rosen_hess.ddf),
    "end module test_differentiate_reference\n",
])

out = Path(__file__).resolve().parents[1] / "test" / "differentiate_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
