program sparse_lobpcg_reference_driver
    use scifort_kinds, only: dp
    use scifort_sparse, only: csr_matrix, csr_from_dense
    use scifort_sparse_linalg, only: lobpcg
    implicit none
    integer :: cases, case_num, n, k, ny, mode, i, j, stat, steps, nend
    type(csr_matrix) :: a, b, m
    real(dp), allocatable :: dense(:,:), dense_b(:,:), dense_m(:,:), x0(:,:), &
        y(:,:), val(:), vec(:,:), res(:), bv(:,:), orth(:,:), product(:,:)
    real(dp) :: orth_error, constraint_error

    read(*,*) cases
    do case_num=1,cases
        read(*,*) n,k,ny,mode
        allocate(dense(n,n), dense_b(n,n), dense_m(n,n), x0(n,k),y(n,ny))
        do i=1,n
            read(*,*) (dense(i,j),j=1,n)
        end do
        do i=1,n
            read(*,*) (dense_b(i,j),j=1,n)
        end do
        do i=1,n
            read(*,*) (dense_m(i,j),j=1,n)
        end do
        do i=1,n
            read(*,*) (x0(i,j),j=1,k)
        end do
        if (ny>0) then
            do i=1,n
                read(*,*) (y(i,j),j=1,ny)
            end do
        end if
        a=csr_from_dense(dense)
        b=csr_from_dense(dense_b)
        m=csr_from_dense(dense_m)
        select case(mode)
        case(0)
            call lobpcg(a,x0,val,vec,stat,largest=.true.,tol=1.0e-7_dp, &
                maxiter=160,iterations=steps,residual_norms=res)
        case(1)
            call lobpcg(a,x0,val,vec,stat,largest=.false.,tol=1.0e-7_dp, &
                maxiter=160,iterations=steps,residual_norms=res)
        case(2)
            call lobpcg(a,x0,val,vec,stat,largest=.true.,tol=1.0e-7_dp, &
                maxiter=160,b=b,iterations=steps,residual_norms=res)
        case(3)
            call lobpcg(a,x0,val,vec,stat,largest=.false.,tol=1.0e-7_dp, &
                maxiter=160,b=b,y=y,iterations=steps,residual_norms=res)
        case(4)
            call lobpcg(a,x0,val,vec,stat,largest=.true.,tol=1.0e-7_dp, &
                maxiter=160,m=m,iterations=steps,residual_norms=res)
        case(5)
            call lobpcg(a,x0,val,vec,stat,largest=.false.,tol=1.0e-7_dp, &
                maxiter=160,jacobi=.true.,iterations=steps,residual_norms=res)
        case default
            error stop 'Unknown mode'
        end select
        orth_error=huge(1.0_dp)
        constraint_error=huge(1.0_dp)
        if (size(vec,1)==n) then
            if (mode==2 .or. mode==3) then
                bv=matmul(dense_b,vec)
            else
                bv=vec
            end if
            orth=matmul(transpose(vec),bv)
            do i=1,k
                orth(i,i)=orth(i,i)-1.0_dp
            end do
            orth_error=maxval(abs(orth))
            constraint_error=0.0_dp
            if (ny>0) constraint_error=maxval(abs(matmul(transpose(y),bv)))
        end if
        write(*,'(i0,1x,i0)',advance='no') stat,steps
        do i=1,size(val)
            write(*,'(1x,es29.16e3)',advance='no') val(i)
        end do
        do i=1,size(res)
            write(*,'(1x,es29.16e3)',advance='no') res(i)
        end do
        write(*,'(2(1x,es29.16e3))',advance='no') orth_error,constraint_error
        if (size(vec,1)==n) then
            do j=1,k
                do i=1,n
                    write(*,'(1x,es29.16e3)',advance='no') vec(i,j)
                end do
            end do
        end if
        write(*,'(a)') ''
        deallocate(dense,dense_b,dense_m,x0,y)
    end do
end program sparse_lobpcg_reference_driver
