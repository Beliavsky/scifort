#!/usr/bin/env python3
"""Generate deterministic SciPy 1.17 constraint BFGS/SR1 reference minimizers."""
from pathlib import Path
import numpy as np
from scipy.optimize import minimize, NonlinearConstraint, Bounds, SR1, BFGS


def obj(x):
    return (x[0] - 0.55)**2 + 2.0 * (x[1] - 0.3)**2


def jac(x):
    return np.array([2 * (x[0] - 0.55), 4 * (x[1] - 0.3)])


def hess(x):
    return np.diag([2.0, 4.0])


def cons(x):
    return np.array([x[0]**2 - x[1]**2, x[0] + x[1]**2])


def cons_jac(x):
    return np.array([[2*x[0], -2*x[1]], [1.0, 2*x[1]]])


def other(x):
    return np.array([x[0] * x[1]])


def other_jac(x):
    return np.array([[x[1], x[0]]])


def other_hess(x,v):
    return np.array([[0,v[0]],[v[0],0]])


cases = {
    'sr1_equality': (SR1(), [0.2, -np.inf], [0.2, np.inf], None),
    'bfgs_equality': (BFGS(), [0.2, -np.inf], [0.2, np.inf], None),
    'sr1_bounded': (SR1(), [0.2, 0.8], [0.2, np.inf], Bounds([0.0,0.0],[1.5,1.5])),
}
solutions = {}
for name, (strategy, lo, hi, bounds) in cases.items():
    c = NonlinearConstraint(cons, lo, hi, jac=cons_jac, hess=strategy)
    other_constraint = NonlinearConstraint(other, 0.1, np.inf, jac=other_jac, hess=other_hess)
    result = minimize(obj, [0.85, 0.5], method='trust-constr', jac=jac, hess=hess,
                      constraints=[c, other_constraint], bounds=bounds,
                      options=dict(gtol=1e-10, xtol=1e-11, maxiter=500))
    print(name, 'success=',result.success,'status=',result.status,'x=',result.x,
          'f=',result.fun,'violation=',result.constr_violation, 'nit=',result.nit)
    solutions[name] = result.x
    if not result.success:
        raise RuntimeError(f'failure in {name}: {result.message}')

path = Path(__file__).resolve().parents[1] / 'test' / 'optimize_trust_constr_constraint_updates_reference.f90'
with path.open('w', encoding='ascii') as f:
    f.write('! SPDX-License-Identifier: MIT\n')
    f.write('! Generated by tools/generate_optimize_trust_constr_constraint_updates_reference.py\n')
    f.write('module test_optimize_trust_constr_constraint_updates_reference\n')
    f.write('    use scifort_kinds, only : dp\n')
    f.write('    implicit none\n')
    for name, x in solutions.items():
        f.write(f'    real(dp), parameter :: {name}_x(2) = [ &\n')
        f.write(f'        {x[0]:.16e}_dp, {x[1]:.16e}_dp ]\n')
    f.write('end module test_optimize_trust_constr_constraint_updates_reference\n')
print('wrote',path)
