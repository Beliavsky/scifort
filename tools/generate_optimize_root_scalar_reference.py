#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for scalar ``scipy.optimize`` roots."""

from pathlib import Path
import math
import scipy
from scipy import optimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def emit_result(parts, prefix, result):
    parts.append(f"    real(dp), parameter :: {prefix}_root_ref = {fmt(result.root)}\n")
    parts.append(f"    integer, parameter :: {prefix}_iterations_ref = {int(result.iterations)}\n")
    parts.append(f"    integer, parameter :: {prefix}_calls_ref = {int(result.function_calls)}\n")


def cubic(x):
    return x**3 - 1.0


def cubic_prime(x):
    return 3.0 * x*x


def cubic_prime2(x):
    return 6.0 * x


def cos_minus_x(x):
    return math.cos(x) - x


parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_root_scalar_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_root_scalar_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]

for method in ["bisect", "brentq", "brenth", "ridder", "toms748"]:
    r = optimize.root_scalar(cubic, bracket=(0.0, 3.0), method=method)
    emit_result(parts, f"cubic_{method}", r)

for method in ["bisect", "brentq", "brenth", "ridder", "toms748"]:
    r = optimize.root_scalar(cos_minus_x, bracket=(0.0, 1.0), method=method)
    emit_result(parts, f"cos_{method}", r)

r = optimize.root_scalar(cubic, x0=0.5, x1=2.0, method="secant")
emit_result(parts, "cubic_secant", r)
r = optimize.root_scalar(cubic, x0=0.5, fprime=cubic_prime, method="newton")
emit_result(parts, "cubic_newton", r)
r = optimize.root_scalar(cubic, x0=0.5, fprime=cubic_prime, fprime2=cubic_prime2, method="halley")
emit_result(parts, "cubic_halley", r)
r = optimize.root_scalar(cubic, x0=0.5, method="newton")
emit_result(parts, "cubic_numerical_newton", r)

root, r = optimize.newton(cubic, 0.5, full_output=True, disp=False)
parts.append(f"    real(dp), parameter :: direct_secant_root_ref = {fmt(root)}\n")
parts.append(f"    integer, parameter :: direct_secant_iterations_ref = {int(r.iterations)}\n")
parts.append(f"    integer, parameter :: direct_secant_calls_ref = {int(r.function_calls)}\n")

r = optimize.root_scalar(cubic, bracket=(0.0, 3.0), method="brentq", maxiter=1)
emit_result(parts, "cubic_brentq_maxiter1", r)

parts.append("end module test_optimize_root_scalar_reference\n")

out = Path(__file__).resolve().parents[1] / "test" / "optimize_root_scalar_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
