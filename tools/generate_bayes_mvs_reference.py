#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for mvsdist and bayes_mvs."""

from pathlib import Path
import numpy as np
import scipy
from scipy import stats


def fmt(v):
    return f"{float(v):.17e}_dp"


def rvec(name, values):
    a = np.asarray(values, dtype=float).reshape(-1)
    lines = [f"    real(dp), parameter :: {name}({a.size}) = [ &\n"]
    for i, v in enumerate(a):
        suffix = ", &" if i < a.size - 1 else " ]"
        lines.append(f"        {fmt(v)}{suffix}\n")
    return "".join(lines)


def posterior_summary(data, alpha):
    dists = stats.mvsdist(data)
    centers = [d.mean() for d in dists]
    variances = [d.var() for d in dists]
    stds = [d.std() for d in dists]
    intervals = np.asarray([d.interval(alpha) for d in dists])
    ppf25 = [d.ppf(0.25) for d in dists]
    cdf1 = [d.cdf(1.0) for d in dists]
    return centers, variances, stds, intervals, ppf25, cdf1


example = np.array([6., 9., 12., 7., 8., 8., 13.])
centers, variances, stds, int90, ppf25, cdf1 = posterior_summary(example, 0.90)
_, _, _, int95, _, _ = posterior_summary(example, 0.95)

n2 = np.array([1., 2.])
n2_int90 = np.asarray([d.interval(0.90) for d in stats.mvsdist(n2)])

n3 = np.array([1., 2., 3.])
n3_dists = stats.mvsdist(n3)
n3_finite = [n3_dists[0].mean(), n3_dists[2].mean()]
n3_int90 = np.asarray([d.interval(0.90) for d in n3_dists])

matrix_data = np.array([[6., 9., 12.], [7., 8., 8.]])
mat_bayes = stats.bayes_mvs(matrix_data, alpha=0.90)
mat_centers = [r.statistic for r in mat_bayes]
mat_intervals = np.asarray([r.minmax for r in mat_bayes])

large = np.linspace(-2., 3., 1001)
large_dists = stats.mvsdist(large)
large_centers = [d.mean() for d in large_dists]
large_vars = [d.var() for d in large_dists]
large_int90 = np.asarray([d.interval(0.90) for d in large_dists])
large_ppf25 = [d.ppf(0.25) for d in large_dists]

parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_bayes_mvs_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_bayes_mvs_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
    rvec("bayes_example_data_ref", example),
    rvec("bayes_example_centers_ref", centers),
    rvec("bayes_example_variances_ref", variances),
    rvec("bayes_example_stds_ref", stds),
    rvec("bayes_example_interval90_ref", int90.ravel(order="C")),
    rvec("bayes_example_interval95_ref", int95.ravel(order="C")),
    rvec("bayes_example_ppf25_ref", ppf25),
    rvec("bayes_example_cdf1_ref", cdf1),
    rvec("bayes_n2_interval90_ref", n2_int90.ravel(order="C")),
    rvec("bayes_n3_finite_ref", n3_finite),
    rvec("bayes_n3_interval90_ref", n3_int90.ravel(order="C")),
    rvec("bayes_matrix_centers_ref", mat_centers),
    rvec("bayes_matrix_interval90_ref", mat_intervals.ravel(order="C")),
    rvec("bayes_large_centers_ref", large_centers),
    rvec("bayes_large_variances_ref", large_vars),
    rvec("bayes_large_interval90_ref", large_int90.ravel(order="C")),
    rvec("bayes_large_ppf25_ref", large_ppf25),
    "end module test_bayes_mvs_reference\n",
]

out = Path(__file__).resolve().parents[1] / "test" / "test_bayes_mvs_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
