#!/usr/bin/env python3
"""Generate SciPy 1.17 trust-constr three-point objective FD references."""

from pathlib import Path

import numpy as np
from scipy.optimize import Bounds, LinearConstraint, NonlinearConstraint, minimize


def objective(x):
    return (x[0] - 1.0)**2 + 3.0 * (x[1] + 2.0)**2


def hessian(x):
    return np.diag([2.0, 6.0])


def nonlinear_hessian(x, v):
    return np.diag([2.0 * v[0], 0.0])


def fmt(value):
    return f"{float(value):.17e}_dp"


def run():
    quadratic_constraint = NonlinearConstraint(
        lambda x: [x[0]**2 + x[1]], [-1.0], [-1.0], jac="3-point",
        hess=nonlinear_hessian,
    )
    cases = (
        ("unconstrained", [-1.0, 1.0], [], None, {}),
        ("linear", [-1.0, 1.0],
         [LinearConstraint([[1.0, 1.0]], [-1.0], [-1.0])], None, {}),
        ("nonlinear", [-1.0, 1.0], [quadratic_constraint], None, {}),
        ("retained", [0.3, 1.0], [],
         Bounds([0.1, -np.inf], [np.inf, np.inf], keep_feasible=[True, False]), {}),
        ("one_iteration", [-1.0, 1.0], [], None, {"maxiter": 1}),
    )
    lines = [
        "! SPDX-License-Identifier: MIT",
        "! Generated by tools/generate_optimize_trust_constr_objective_fd_reference.py",
        "! SciPy version: 1.17.0",
        "module test_optimize_trust_constr_objective_fd_reference",
        "    use scifort_kinds, only : dp",
        "    implicit none",
    ]
    for name, x0, constraints, bounds, options in cases:
        result = minimize(objective, x0, jac="3-point", hess=hessian,
                          constraints=constraints, bounds=bounds,
                          method="trust-constr", options=options)
        expected_status = 0 if name == "one_iteration" else 1
        assert result.status == expected_status, (name, result.message)
        coords = ", ".join(map(fmt, result.x))
        lines += [
            f"    real(dp), parameter :: {name}_x(2) = [{coords}]",
            f"    real(dp), parameter :: {name}_fun = {fmt(result.fun)}",
            f"    integer, parameter :: {name}_status = {result.status}",
            f"    integer, parameter :: {name}_nit = {result.nit}",
            f"    integer, parameter :: {name}_nfev = {result.nfev}",
            f"    integer, parameter :: {name}_njev = {result.njev}",
            f"    integer, parameter :: {name}_nhev = {result.nhev}",
            f"    integer, parameter :: {name}_cg_niter = {result.cg_niter}",
        ]
        print(name, result.x, result.nit, result.nfev, result.njev, result.nhev,
              result.cg_niter)
    lines += ["end module test_optimize_trust_constr_objective_fd_reference", ""]
    dest = (Path(__file__).resolve().parent.parent / "test" /
            "optimize_trust_constr_objective_fd_reference.f90")
    dest.write_text("\n".join(lines), encoding="ascii")
    print(dest)


if __name__ == "__main__":
    run()
