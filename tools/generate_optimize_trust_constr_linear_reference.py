#!/usr/bin/env python3
"""Generate SciPy 1.17 trust-constr references for constant-matrix blocks."""

from pathlib import Path

import numpy as np
from scipy.optimize import LinearConstraint, NonlinearConstraint, minimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def values(name, data):
    data = np.asarray(data).ravel()
    return (f"    real(dp), parameter :: {name}({len(data)}) = "
            f"[{', '.join(map(fmt, data))}]")


def counts(name, data):
    return f"    integer, parameter :: {name}({len(data)}) = [{', '.join(map(str, data))}]"


def quadratic(x):
    return (x[0] - 1.0)**2 + (x[1] - 2.5)**2


def gradient(x):
    return 2.0 * (x - np.array([1.0, 2.5]))


def hessian(x):
    return 2.0 * np.eye(len(x))


def first(x):
    return np.array([x[0]])


def first_jac(x):
    return np.array([[1.0, 0.0]])


def zero_hess(x, v):
    return np.zeros((len(x), len(x)))


def circle(x):
    return np.array([x @ x])


def circle_jac(x):
    return (2.0 * x)[None, :]


def circle_hess(x, v):
    return (2.0 * v[0]) * np.eye(len(x))


def circle_obj(x):
    return (x[0] - 2.0)**2 + (x[1] - 1.0)**2


def circle_grad(x):
    return 2.0 * (x - np.array([2.0, 1.0]))


def generate():
    sum_matrix = np.array([[1.0, 1.0]])
    first_matrix = np.array([[1.0, 0.0]])
    equality = LinearConstraint(sum_matrix, 2.0, 2.0)
    cases = (
        ("linear_only", quadratic, gradient, hessian, [0.6, 1.4],
         [equality, LinearConstraint(first_matrix, 0.5, np.inf)]),
        ("linear_multirow", quadratic, gradient, hessian, [0.6, 1.4],
         [LinearConstraint(np.vstack([sum_matrix, first_matrix]),
                           [2.0, 0.5], [2.0, np.inf])]),
        ("linear_nonlinear", quadratic, gradient, hessian, [0.6, 1.4],
         [equality, NonlinearConstraint(first, 0.5, np.inf,
                                        jac=first_jac, hess=zero_hess)]),
        ("linear_three_point", quadratic, gradient, hessian, [0.6, 1.4],
         [equality, NonlinearConstraint(first, 0.5, np.inf,
                                        jac='3-point', hess=zero_hess)]),
        ("nonlinear_linear", circle_obj, circle_grad, hessian, [0.8, 0.6],
         [NonlinearConstraint(circle, 1.0, 1.0, jac=circle_jac,
                              hess=circle_hess),
          LinearConstraint([[0.0, 1.0]], 0.0, np.inf)]),
    )
    lines = ["! SPDX-License-Identifier: MIT",
             "! Generated by tools/generate_optimize_trust_constr_linear_reference.py",
             "! SciPy version: 1.17.0",
             "module test_optimize_trust_constr_linear_reference",
             "    use scifort_kinds, only : dp",
             "    implicit none"]
    for name, fun, jac, hess, start, constraints in cases:
        res = minimize(fun, start, method='trust-constr', jac=jac, hess=hess,
                       constraints=constraints, options={'gtol': 1e-9 if name == 'nonlinear_linear' else 1e-8,
                                                         'xtol': 1e-10 if name == 'nonlinear_linear' else 1e-8,
                                                         'barrier_tol': 1e-8})
        assert res.success and res.status == 1, res.message
        lines += [values(name + '_x', res.x),
                  f"    real(dp), parameter :: {name}_fun = {fmt(res.fun)}",
                  f"    integer, parameter :: {name}_nit = {res.nit}",
                  f"    integer, parameter :: {name}_nfev = {res.nfev}",
                  values(name + '_constr', np.concatenate(res.constr)),
                  counts(name + '_constr_nfev', res.constr_nfev),
                  counts(name + '_constr_njev', res.constr_njev),
                  counts(name + '_constr_nhev', res.constr_nhev)]
    lines += ["end module test_optimize_trust_constr_linear_reference", ""]
    output = Path(__file__).resolve().parent.parent / 'test' / 'optimize_trust_constr_linear_reference.f90'
    output.write_text('\n'.join(lines), encoding='ascii')
    print(output)


if __name__ == '__main__':
    generate()
