#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for binned statistics."""

from pathlib import Path
import numpy as np
import scipy
from scipy import stats


def fmt(v):
    return f"{float(v):.17e}_dp"


def rvec(name, values):
    a = np.asarray(values, dtype=float).reshape(-1)
    lines = [f"    real(dp), parameter :: {name}({a.size}) = [ &\n"]
    for i, v in enumerate(a):
        suffix = ", &" if i < a.size - 1 else " ]"
        lines.append(f"        {fmt(v)}{suffix}\n")
    return "".join(lines)


def ivec(name, values):
    a = np.asarray(values, dtype=int).reshape(-1)
    lines = [f"    integer, parameter :: {name}({a.size}) = [ &\n"]
    for i, v in enumerate(a):
        suffix = ", &" if i < a.size - 1 else " ]"
        lines.append(f"        {int(v)}{suffix}\n")
    return "".join(lines)


def rmat(name, values):
    a = np.asarray(values, dtype=float)
    flat = a.flatten(order="F")
    lines = [f"    real(dp), parameter :: {name}({a.shape[0]},{a.shape[1]}) = reshape([ &\n"]
    for i, v in enumerate(flat):
        suffix = ", &" if i < flat.size - 1 else " ], &"
        lines.append(f"        {fmt(v)}{suffix}\n")
    lines.append(f"        [{a.shape[0]},{a.shape[1]}])\n")
    return "".join(lines)


def imat(name, values):
    a = np.asarray(values, dtype=int)
    flat = a.flatten(order="F")
    lines = [f"    integer, parameter :: {name}({a.shape[0]},{a.shape[1]}) = reshape([ &\n"]
    for i, v in enumerate(flat):
        suffix = ", &" if i < flat.size - 1 else " ], &"
        lines.append(f"        {int(v)}{suffix}\n")
    lines.append(f"        [{a.shape[0]},{a.shape[1]}])\n")
    return "".join(lines)


x1 = np.array([1., 1., 2., 5., 7.])
v1 = np.array([1., 1., 2., 1.5, 3.])
stats1 = {name: stats.binned_statistic(x1, v1, statistic=name, bins=2)
          for name in ["sum", "mean", "std", "median", "count", "min", "max"]}

x_out = np.array([-1., 0., 1., 2., 3., 4., 5., 6.])
v_out = np.array([8., 1., 2., 3., 4., 5., 6., 9.])
out_ref = stats.binned_statistic(x_out, v_out, "mean", bins=[0., 2., 5.])
custom_ref = stats.binned_statistic(
    x_out, v_out, lambda a: np.ptp(a) if len(a) else -99.,
    bins=[0., 0.5, 0.75, 5.]
)
const_ref = stats.binned_statistic(np.array([3., 3.]), np.array([1., 2.]), "count", bins=2)

x2 = np.array([-0.1, 0.1, 0.9, 1.1, 1.9, 2.0, 2.1])
y2 = np.array([0.2, 0.2, 1.2, 0.8, 1.8, 2.0, 1.0])
v2 = np.arange(1, 8, dtype=float)
r2 = stats.binned_statistic_2d(
    x2, y2, v2, "mean", bins=[2, 2], range=[[0, 2], [0, 2]]
)
r2e = stats.binned_statistic_2d(
    x2, y2, v2, "mean", bins=[2, 2], range=[[0, 2], [0, 2]],
    expand_binnumbers=True
)
r2count = stats.binned_statistic_2d(
    x2, y2, None, "count", bins=[2, 2], range=[[0, 2], [0, 2]]
)

sample = np.array([
    [-.1, .2, .2], [.1, .2, .2], [.9, 1.2, .9], [1.1, .8, 1.2],
    [1.9, 1.8, 1.8], [2., 2., 2.], [2.1, 1., 1.]
])
vd = np.arange(1, 8, dtype=float)
rdd = stats.binned_statistic_dd(
    sample, vd, "sum", bins=[2, 2, 2], range=[[0, 2], [0, 2], [0, 2]]
)
rdde = stats.binned_statistic_dd(
    sample, vd, "sum", bins=[2, 2, 2], range=[[0, 2], [0, 2], [0, 2]],
    expand_binnumbers=True
)
rddcount = stats.binned_statistic_dd(
    sample, None, "count", bins=[2, 2, 2], range=[[0, 2], [0, 2], [0, 2]]
)

edges_dd = [np.array([0., 1., 2.]), np.array([0., .5, 2.]), np.array([0., 1.5, 2.])]
rdd_exp = stats.binned_statistic_dd(
    sample, None, "count", bins=edges_dd, expand_binnumbers=True
)

parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_binned_statistic_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_binned_statistic_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
    rvec("binned_x1_ref", x1),
    rvec("binned_v1_ref", v1),
    rvec("binned_edges1_ref", stats1["mean"].bin_edges),
    ivec("binned_numbers1_ref", stats1["mean"].binnumber),
]
for name in ["sum", "mean", "std", "median", "count", "min", "max"]:
    parts.append(rvec(f"binned_{name}1_ref", stats1[name].statistic))
parts += [
    rvec("binned_xout_ref", x_out),
    rvec("binned_vout_ref", v_out),
    rvec("binned_out_edges_ref", out_ref.bin_edges),
    rvec("binned_out_mean_ref", out_ref.statistic),
    ivec("binned_out_numbers_ref", out_ref.binnumber),
    rvec("binned_custom_edges_ref", custom_ref.bin_edges),
    rvec("binned_custom_ref", custom_ref.statistic),
    ivec("binned_custom_numbers_ref", custom_ref.binnumber),
    rvec("binned_const_edges_ref", const_ref.bin_edges),
    rvec("binned_const_count_ref", const_ref.statistic),
    ivec("binned_const_numbers_ref", const_ref.binnumber),
    rvec("binned_x2_ref", x2),
    rvec("binned_y2_ref", y2),
    rvec("binned_v2_ref", v2),
    rmat("binned_2d_mean_ref", r2.statistic),
    rmat("binned_2d_count_ref", r2count.statistic),
    rvec("binned_2d_xedge_ref", r2.x_edge),
    rvec("binned_2d_yedge_ref", r2.y_edge),
    ivec("binned_2d_numbers_ref", r2.binnumber),
    imat("binned_2d_expanded_ref", r2e.binnumber),
    rmat("binned_dd_sample_ref", sample),
    rvec("binned_dd_values_ref", vd),
    rvec("binned_dd_sum_ref", rdd.statistic.ravel(order="C")),
    rvec("binned_dd_count_ref", rddcount.statistic.ravel(order="C")),
    ivec("binned_dd_numbers_ref", rdd.binnumber),
    imat("binned_dd_expanded_ref", rdde.binnumber),
    rvec("binned_dd_explicit_count_ref", rdd_exp.statistic.ravel(order="C")),
    imat("binned_dd_explicit_expanded_ref", rdd_exp.binnumber),
    "end module test_binned_statistic_reference\n",
]

out = Path(__file__).resolve().parents[1] / "test" / "test_binned_statistic_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
