"""Generate SciPy reference minimizers for numerical constraint Hessians."""
from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import Bounds, NonlinearConstraint, minimize


def objective(x):
    return x[0] ** 2 + 3.0 * x[1] ** 2 + 0.1 * x[0] * x[1]


def gradient(x):
    return np.array([2.0 * x[0] + 0.1 * x[1], 6.0 * x[1] + 0.1 * x[0]])


def objective_hessian(x):
    return np.array([[2.0, 0.1], [0.1, 6.0]])


def constraint(x):
    return np.array([x[0] ** 2 + np.sin(x[1])])


def constraint_jacobian(x):
    return np.array([[2.0 * x[0], np.cos(x[1])]])


results = {}
for scheme in ('2-point', '3-point'):
    block = NonlinearConstraint(constraint, [1.0], [1.0],
                                jac=constraint_jacobian, hess=scheme)
    result = minimize(objective, [0.8, 0.9], jac=gradient,
                      hess=objective_hessian, method='trust-constr',
                      constraints=[block], options={'gtol': 1e-9})
    if not result.success or result.constr_violation > 1e-7:
        raise RuntimeError(f'{scheme} Hessian reference did not converge: {result.message}')
    results[scheme] = result
    print(f'SciPy {scipy.__version__} {scheme}: x={result.x.tolist()}, '
          f'nit={result.nit}, constr_njev={result.constr_njev}, '
          f'constr_nhev={result.constr_nhev}')

bounded_constraint = NonlinearConstraint(constraint, [1.0], [np.inf],
                                         jac=constraint_jacobian,
                                         hess='3-point', keep_feasible=True)
bounded = minimize(objective, [0.8, 0.9], jac=gradient, method='trust-constr',
                   bounds=Bounds([0.0, -2.0], [0.8, 2.0], keep_feasible=True),
                   constraints=[bounded_constraint],
                   options={'gtol': 1e-8, 'maxiter': 300})
if not bounded.success or bounded.constr_violation > 1e-7:
    raise RuntimeError(f'bounded Hessian reference did not converge: {bounded.message}')
print(f'SciPy {scipy.__version__} 3-point with BFGS/bounds: '
      f'x={bounded.x.tolist()}, nit={bounded.nit}')

lines = [
    '! SPDX-License-Identifier: MIT',
    '! Generated by tools/generate_optimize_trust_constr_constraint_hess_fd_reference.py',
    f'! SciPy version: {scipy.__version__}',
    'module test_optimize_trust_constr_constraint_hess_fd_reference',
    '    use scifort_kinds, only : dp',
    '    implicit none',
]
for scheme in ('2-point', '3-point'):
    label = 'two_point_x' if scheme == '2-point' else 'three_point_x'
    x = results[scheme].x
    lines.append(f'    real(dp), parameter :: {label}(2) = [ &')
    lines.append(f'        {x[0]:.17e}_dp, {x[1]:.17e}_dp ]')
lines.append('    real(dp), parameter :: bounded_x(2) = [ &')
lines.append(f'        {bounded.x[0]:.17e}_dp, {bounded.x[1]:.17e}_dp ]')
lines.append('end module test_optimize_trust_constr_constraint_hess_fd_reference')
target = Path(__file__).resolve().parent.parent / 'test/optimize_trust_constr_constraint_hess_fd_reference.f90'
target.write_text('\n'.join(lines) + '\n', encoding='ascii')
print(f'Generated {target}')
