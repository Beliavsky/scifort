#!/usr/bin/env python3
"""Generate scalar elementwise.bracket_minimum references using SciPy 1.17."""

from pathlib import Path

import scipy
from scipy.optimize import elementwise


def right(x):
    return (x - 5.0) ** 2


def left(x):
    return (x + 3.0) ** 2


def initial(x):
    return x**2


def constant(x):
    return 0.0 * x


def monotone(x):
    return -x


def monotone_left(x):
    return x


def plateau(x):
    return 0.0 if x >= 1.0 else (x - 1.0) ** 2


def shifted(x):
    return (x - 1.0) ** 2 + 2.0


cases = [
    ("right", right, 0.0, {}),
    ("left", left, 0.0, {}),
    ("initial", initial, 0.0, {}),
    ("rightfactor3", right, 0.0, {"factor": 3.0}),
    ("rightbound", right, 0.0, {"xmax": 6.0}),
    ("leftbound", left, 0.0, {"xmin": -5.0}),
    ("custom", right, 0.0, {"xl0": -1.0, "xr0": 2.0}),
    ("customleft", left, 0.0, {"xl0": -1.0, "xr0": 1.0}),
    ("max0", right, 0.0, {"maxiter": 0}),
    ("max2", right, 0.0, {"maxiter": 2}),
    ("constant", constant, 0.0, {"maxiter": 3}),
    ("plateau", plateau, 0.0, {}),
    ("shifted", shifted, 0.0, {}),
    ("boundboth", initial, 0.0, {"xmin": -0.1, "xmax": 0.1}),
    ("rightlimit", monotone, 0.0, {"xmax": 1.0}),
    ("leftlimit", monotone_left, 0.0, {"xmin": -1.0}),
    ("limitstart", monotone, 0.0, {"xl0": -0.2, "xr0": 1.0, "xmax": 1.0}),
]

lines = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_bracket_minimum_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_bracket_minimum_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]
for label, fun, start, opts in cases:
    result = elementwise.bracket_minimum(fun, start, **opts)
    for name, value in zip(("xl", "xm", "xr", "fl", "fm", "fr"),
                           (*result.bracket, *result.f_bracket)):
        lines.append(f"    real(dp), parameter :: {label}_{name}_ref = {float(value):.17e}_dp\n")
    for name in ("nit", "nfev", "status"):
        lines.append(f"    integer, parameter :: {label}_{name}_ref = {int(getattr(result, name))}\n")
lines.append("end module test_optimize_bracket_minimum_reference\n")
out = Path(__file__).resolve().parents[1] / "test" / "optimize_bracket_minimum_reference.f90"
out.write_text("".join(lines), encoding="ascii")
print(f"Wrote {out} with {len(cases)} SciPy {scipy.__version__} cases")
