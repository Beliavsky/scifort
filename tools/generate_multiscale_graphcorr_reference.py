#!/usr/bin/env python3
"""Generate deterministic SciPy 1.17 references for multiscale_graphcorr."""
from pathlib import Path
import warnings
import numpy as np
import scipy
from scipy import stats
from scipy.spatial.distance import cdist

assert scipy.__version__ == "1.17.0", scipy.__version__


def mgc(x, y, **kwargs):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        return stats.multiscale_graphcorr(x, y, reps=0, random_state=1, **kwargs)


x_quad = np.array([0., 1., 2., 3., 4., 5.])
y_quad = np.array([0., 1., 4., 9., 16., 25.])
quad = mgc(x_quad, y_quad)

x_mv = np.array([
    [0., 0.], [1., 0.], [0., 1.], [1., 1.],
    [2., 1.], [1., 2.], [2., 2.],
])
y_mv = np.array([0., 1., 1., 2., 3., 2., 4.])
mv = mgc(x_mv, y_mv)

y_custom = np.array([
    [0., 0.], [1., 1.], [1., 0.], [2., 1.],
    [3., 1.], [2., 2.], [4., 2.],
])
custom = mgc(x_mv, y_custom, compute_distance=lambda z: cdist(z, z, metric="cityblock"))

x_tied = np.array([0., 0., 1., 2., 3., 3.])[:, None]
y_tied = np.array([0., 1., 1., 2., 4., 5.])[:, None]
dx_tied = cdist(x_tied, x_tied)
dy_tied = cdist(y_tied, y_tied)
pre = mgc(dx_tied, dy_tied, compute_distance=None)

u = np.array([[0.], [1.], [2.], [3.], [4.]])
v = np.array([[5.], [6.], [7.], [8.], [9.], [10.]])
two = mgc(u, v)


def fr(x):
    text = f"{float(x):.17g}"
    if "e" not in text.lower() and "." not in text:
        text += ".0"
    return text + "_dp"


def vec(name, values):
    vals = [fr(v) for v in values]
    lines = [f"    real(dp), parameter :: {name}({len(vals)}) = [ &"]
    for i in range(0, len(vals), 3):
        chunk = ", ".join(vals[i:i + 3])
        suffix = ", &" if i + 3 < len(vals) else " &"
        lines.append(f"        {chunk}{suffix}")
    lines.append("    ]")
    return "\n".join(lines) + "\n"


def mat(name, values):
    m, n = values.shape
    vals = [fr(v) for v in values.flatten(order="F")]
    lines = [f"    real(dp), parameter :: {name}({m}, {n}) = reshape([ &"]
    for i in range(0, len(vals), 3):
        chunk = ", ".join(vals[i:i + 3])
        suffix = ", &" if i + 3 < len(vals) else " &"
        lines.append(f"        {chunk}{suffix}")
    lines.append(f"    ], [{m}, {n}])")
    return "\n".join(lines) + "\n"


out = [
    "! Generated by tools/generate_multiscale_graphcorr_reference.py with SciPy 1.17.0.\n",
    "module multiscale_graphcorr_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
    "    public\n\n",
]
for name, res in [("quad", quad), ("mv", mv), ("custom", custom), ("pre", pre), ("two", two)]:
    out.append(f"    real(dp), parameter :: {name}_stat = {fr(res.statistic)}\n")
    scale = res.mgc_dict["opt_scale"]
    out.append(
        f"    integer, parameter :: {name}_scale(2) = [{int(scale[0])}, {int(scale[1])}]\n"
    )
    out.append(mat(f"{name}_map", res.mgc_dict["mgc_map"]))
out.append("end module multiscale_graphcorr_reference\n")
Path("test/multiscale_graphcorr_reference.f90").write_text("".join(out), encoding="ascii")
