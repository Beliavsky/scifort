"""Generate a NumPy/ctypes layer using native declarations and explicit Python policy."""
from __future__ import annotations
import argparse
import copy
import json
import keyword
import math
from pathlib import Path
from pprint import pformat
import sys

import generate
import generate_arrays


def py_name(value):
    generate.identifier(value)
    if keyword.iskeyword(value):
        raise ValueError(f'Python keyword is not an API name: {value}')
    return value


def artifacts(config_path, root):
    policy = json.loads(config_path.read_text(encoding='utf-8'))
    if (not isinstance(policy, dict) or set(policy) - {'array_groups'} != {'schema_version', 'output_directory', 'groups'}
            or type(policy['schema_version']) is not int or policy['schema_version'] != 1):
        raise ValueError('Python policy requires schema_version=1, output_directory and groups')
    if (not isinstance(policy['output_directory'], str)
            or not isinstance(policy['groups'], dict) or not policy['groups']):
        raise ValueError('output_directory must be a string and groups a nonempty object')
    output = (root / policy['output_directory']).resolve()
    lines = ['# SPDX-License-Identifier: MIT', '# Generated by cabi_generator; do not edit.',
             'from ._runtime import Distribution, Library, ArrayGroup', '']
    result, protected, groups = {}, {config_path.resolve()}, []
    for group, options in sorted(policy['groups'].items()):
        py_name(group)
        if group in {'api', 'library', 'distribution', 'path'}:
            raise ValueError(f'{group}: reserved generated API name')
        if not isinstance(options, dict) or set(options) != {'manifest', 'prefix', 'defaults', 'existing_functions'}:
            raise ValueError(f'{group}: invalid Python group policy')
        if not isinstance(options['manifest'], str) or not isinstance(options['prefix'], str):
            raise ValueError('manifest and prefix must be strings')
        manifest_path = (root / options['manifest']).resolve()
        config = json.loads(manifest_path.read_text(encoding='utf-8'))
        # Validate the complete original C manifest before extending excluded existing methods.
        generate.generate(config, root)
        protected.update({manifest_path, (root / config['source']).resolve()})
        protected.update((root / p).resolve() for p in config['outputs'].values())
        api = generate.public_api(root / config['source'], config['module'])
        if config.get('subroutines') or not config['functions']:
            raise ValueError('Python groups currently require scalar/elemental function manifests')
        functions = copy.deepcopy(config['functions'])
        extras = options['existing_functions']
        if not isinstance(extras, dict) or set(extras) - (set(config['excluded']) | {n for n, e in functions.items()
                if e.get('existing_scalar_symbol') and not e.get('vector_symbol')}):
            raise ValueError(f'{group}: existing_functions must refer to excluded exports or external scalar/bulk entries')
        for native, extra in extras.items():
            if not isinstance(extra, dict) or 'elementwise_symbol' in extra:
                raise ValueError('configure elementwise_symbol in the primary C manifest')
            existing = functions.get(native, {}).get('existing_scalar_symbol')
            if existing and extra.get('symbol') != existing:
                raise ValueError('existing scalar mapping must match the primary C manifest')
            functions[native] = dict(functions.get(native, {}), **extra)
            functions[native].pop('existing_scalar_symbol', None)
        defaults = options['defaults']
        if not isinstance(defaults, dict) or not all(type(v) in (int, float) and math.isfinite(v)
                                                   for v in defaults.values()):
            raise ValueError('defaults must be explicit finite real numbers')
        specs, methods, used_defaults = {}, [], set()
        compat = copy.deepcopy(config)
        compat['functions'] = {}
        for native, entry in sorted(functions.items()):
            if not native.startswith(options['prefix']):
                raise ValueError(f'{native}: does not match configured prefix')
            method = py_name(native[len(options['prefix']):])
            if method in {'out'}:
                raise ValueError('out is reserved by the Python array interface')
            args, optional, elemental = generate.signature(api[native], config['kind_name'])
            if not elemental or not entry.get('vector_symbol') or entry.get('array_argument') not in args:
                raise ValueError(f'{native}: Python requires scalar and elemental bulk symbols')
            scalar = entry.get('symbol') or entry.get('existing_scalar_symbol')
            generate.identifier(scalar)
            varying = entry['array_argument']
            parameters = [a for a in args if a != varying]
            if set(defaults) - set(parameters):
                raise ValueError(f'{native}: default does not name a uniform parameter')
            used_defaults.update(defaults)
            signature = []
            seen_default = False
            for a in parameters:
                py_name(a)
                if a in {'self', 'out'}:
                    raise ValueError(f'{a}: reserved Python argument')
                if a in defaults:
                    seen_default = True
                    signature.append(f'{a}={defaults[a]!r}')
                elif seen_default:
                    raise ValueError('required parameters must precede defaults')
                else:
                    signature.append(a)
            py_name(varying)
            if varying in {'self', 'out'}:
                raise ValueError(f'{varying}: reserved Python argument')
            specs[method] = dict(scalar=scalar, bulk=entry['vector_symbol'], arguments=args,
                                 array=varying, parameters=parameters)
            if entry.get('elementwise_symbol'):
                specs[method]['elementwise'] = entry['elementwise_symbol']
            params = ', '.join(parameters) + (',' if len(parameters) == 1 else '')
            declarations = ', '.join(['self', varying, *signature, '*', 'out=None'])
            description = ('broadcastable real inputs, optional array output buffer.'
                           if entry.get('elementwise_symbol') else
                           'scalar parameters, optional array output buffer.')
            methods += [f'    def {method}({declarations}):',
                        f'        """Evaluate {native}; {description}"""',
                        f'        return self._evaluate({method!r}, {varying}, ({params}), out)', '']
            # A small standalone shared library needs the scalar symbols normally in api.f90.
            if entry.get('existing_scalar_symbol') or native in extras:
                compatibility = copy.deepcopy(entry)
                compatibility.pop('existing_scalar_symbol', None)
                compatibility.pop('elementwise_symbol', None)
                compatibility['symbol'] = scalar
                if native not in extras:
                    for key in ('vector_symbol', 'array_argument', 'array_style', 'finite', 'positive'):
                        compatibility.pop(key, None)
                compat['functions'][native] = compatibility
        if used_defaults != set(defaults):
            raise ValueError('unused Python default')
        class_name = group.capitalize()
        groups.append((group, class_name))
        lines += [f'class {class_name}(Distribution):', '    _specs = ' + pformat(specs, width=96).replace('\n', '\n    '), '', *methods]
        compat['excluded'] = {name: 'Provided by the primary C ABI build, not the standalone supplement.'
                              for name in api if name not in compat['functions']}
        compat['wrapper_module'] = f'cg_python_{group}_compat'
        compat['outputs'] = {key: str(output.parent / 'native' / f'{group}_compat.{ext}')
                             for key, ext in [('fortran', 'f90'), ('header', 'h'), ('coverage', 'json')]}
        result.update(generate.generate(compat, root))
    array_lines, array_groups, array_protected = generate_arrays.prepare(policy, root, py_name)
    lines += array_lines
    groups += array_groups
    protected.update(array_protected)
    lines += ['class API(Library):', '    """Explicit shared-library owner exposing the configured distribution and array groups."""',
              '    def __init__(self, path, *, dll_directories=()):',
              '        super().__init__(path, dll_directories=dll_directories)']
    lines += [f'        self.{group} = {cls}(self._library)' for group, cls in groups]
    lines += ['', '__all__ = ["API"]', '']
    result[output / '_generated.py'] = '\n'.join(lines)
    result[output / '_runtime.py'] = Path(__file__).with_name('python_runtime.py').read_text(encoding='utf-8-sig')
    if result.keys() & protected:
        raise ValueError('Python outputs must not overwrite input configurations or C artifacts')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config', type=Path)
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        outputs = artifacts(args.config, args.root.resolve())
        if args.check:
            stale = [str(p) for p, text in outputs.items()
                     if not p.exists() or p.read_text(encoding='utf-8') != text]
            if stale:
                raise ValueError('missing or stale Python artifacts: ' + ', '.join(stale))
        else:
            for path, text in outputs.items():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8', newline='\n')
        print(f'{"Checked" if args.check else "Generated"} {len(outputs)} Python binding artifacts')
        return 0
    except (ValueError, OSError, generate.FortranSyntaxError) as error:
        print(f'cabi_generator Python: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
