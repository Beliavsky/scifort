#!/usr/bin/env python3
"""Generate SciPy 1.17 numerical references for independent constraints."""

from pathlib import Path

import numpy as np
from scipy.optimize import NonlinearConstraint, minimize


def objective(x):
    return (x[0] - 1.0) ** 2 + (x[1] - 2.5) ** 2


def gradient(x):
    return np.array([2.0 * (x[0] - 1.0), 2.0 * (x[1] - 2.5)])


def objective_hessian(x):
    return 2.0 * np.eye(x.size)


def equality(x):
    return np.array([x[0] + x[1]])


def inequality(x):
    return np.array([x[0]])


def equality_jac(x):
    return np.array([[1.0, 1.0]])


def inequality_jac(x):
    return np.array([[1.0, 0.0]])


def zero_hess(x, v):
    return np.zeros((x.size, x.size))


def fmt(x):
    return f"{float(x):.17e}_dp"


def array(name, v, typ="real"):
    v = np.asarray(v)
    if typ == "real":
        values = ", ".join(fmt(x) for x in v)
        return f"    real(dp), parameter :: {name}({len(v)}) = [{values}]"
    values = ", ".join(str(int(x)) for x in v)
    return f"    integer, parameter :: {name}({len(v)}) = [{values}]"


def generate():
    lines = [
        "! SPDX-License-Identifier: MIT",
        "! Generated by tools/generate_optimize_trust_constr_objects_reference.py",
        "! SciPy version: 1.17.0",
        "module test_optimize_trust_constr_objects_reference",
        "    use scifort_kinds, only : dp",
        "    implicit none",
    ]
    for scheme in ("analytic", "2-point", "3-point"):
        key = {
            "analytic": "objects_analytic",
            "2-point": "objects_mixed",
            "3-point": "objects_three_point",
        }[scheme]
        c = [
            NonlinearConstraint(equality, 2.0, 2.0, jac=equality_jac, hess=zero_hess),
            NonlinearConstraint(inequality, 0.5, np.inf,
                                jac=inequality_jac if scheme == "analytic" else scheme,
                                hess=zero_hess),
        ]
        res = minimize(
            objective, [0.6, 1.4], jac=gradient, hess=objective_hessian,
            constraints=c, method="trust-constr",
            options={"gtol": 1e-8, "xtol": 1e-8, "barrier_tol": 1e-8},
        )
        assert res.success and res.status == 1, res.message
        lines.extend([
            array(f"{key}_x", res.x),
            f"    real(dp), parameter :: {key}_fun = {fmt(res.fun)}",
            f"    integer, parameter :: {key}_nit = {res.nit}",
            f"    integer, parameter :: {key}_nfev = {res.nfev}",
            array(f"{key}_constr", np.concatenate(res.constr)),
            array(f"{key}_constr_nfev", res.constr_nfev, "int"),
            array(f"{key}_constr_njev", res.constr_njev, "int"),
            array(f"{key}_constr_nhev", res.constr_nhev, "int"),
        ])
    lines.extend(["end module test_optimize_trust_constr_objects_reference", ""])
    root = Path(__file__).resolve().parent.parent
    output = root / "test" / "optimize_trust_constr_objects_reference.f90"
    output.write_text("\n".join(lines), encoding="ascii")
    print(f"Wrote {output}")


if __name__ == "__main__":
    generate()
