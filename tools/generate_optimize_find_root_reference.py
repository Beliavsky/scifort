#!/usr/bin/env python3
"""Generate scalar Chandrupatla root references with SciPy 1.17."""

from pathlib import Path
import math
import numpy as np
import scipy
from scipy.optimize import elementwise


def linear(x):
    return x - 1.25


def cubic(x):
    return x**3 - 2*x - 5


def cosine(x):
    return np.cos(x) - x


def exponential(x):
    return np.exp(x) - 3


def cubed(x):
    return (x - 0.3)**3


def left_zero(x):
    return x


def right_zero(x):
    return x - 2


def invalid(x):
    return x*x + 1


def negative(x):
    return x + 2.3


def flat(x):
    return 0*x


cases = [
    ('linear', linear, (0., 4.), {}),
    ('cubic', cubic, (2., 4.), {}),
    ('cosine', cosine, (0., 1.), {}),
    ('exponential', exponential, (0., 2.), {}),
    ('cubed', cubed, (-1., 1.), {}),
    ('reversed', cubic, (4., 2.), {}),
    ('left_zero', left_zero, (0., 2.), {}),
    ('right_zero', right_zero, (0., 2.), {}),
    ('invalid', invalid, (-1., 1.), {}),
    ('max0', cosine, (0., 1.), {'maxiter': 0}),
    ('max1', cosine, (0., 1.), {'maxiter': 1}),
    ('max2', cosine, (0., 1.), {'maxiter': 2}),
    ('xatol', cosine, (0., 1.), {'tolerances': {'xatol': 0.2}}),
    ('fatol', cosine, (0., 1.), {'tolerances': {'fatol': 0.2}}),
    ('frtol', cosine, (0., 1.), {'tolerances': {'frtol': 0.2}}),
    ('strict', cosine, (0., 1.), {'tolerances': {'xatol': 0., 'xrtol': 0., 'fatol': 0., 'frtol': 0.}, 'maxiter': 100}),
    ('negative', negative, (-4., -1.), {}),
    ('flat', flat, (0., 1.), {}),
]
lines = [
    '! SPDX-License-Identifier: MIT\n',
    '! Generated by tools/generate_optimize_find_root_reference.py\n',
    f'! SciPy version: {scipy.__version__}\n',
    'module test_optimize_find_root_reference\n',
    '    use scifort_kinds, only : dp\n',
    '    implicit none\n',
]
for label, fun, bracket, kw in cases:
    res = elementwise.find_root(fun, bracket, **kw)
    values = (res.x, res.f_x, *res.bracket, *res.f_bracket)
    for field, value in zip(('x', 'f_x', 'xl', 'xr', 'fl', 'fr'), values):
        z = float(value)
        code = (f'{z:.17e}_dp' if math.isfinite(z) else '0.0_dp ! nonfinite in SciPy')
        lines.append(f'    real(dp), parameter :: {label}_{field}_ref = {code}\n')
    for field in ('nit', 'nfev', 'status'):
        lines.append(f'    integer, parameter :: {label}_{field}_ref = {int(getattr(res, field))}\n')
lines.append('end module test_optimize_find_root_reference\n')
out = Path(__file__).resolve().parents[1] / 'test' / 'optimize_find_root_reference.f90'
out.write_text(''.join(lines), encoding='ascii')
print(f'Wrote {out} with {len(cases)} SciPy {scipy.__version__} reference cases')
