#!/usr/bin/env python3
"""Generate SciPy trust-constr reference results for Hessian products."""
from pathlib import Path
import numpy as np
import scipy
from scipy.optimize import Bounds, LinearConstraint, NonlinearConstraint, minimize


def objective(x):
    return (x[0] - 1.0) ** 2 + 2.0 * (x[1] + 2.0) ** 2


def gradient(x):
    return np.array([2.0 * (x[0] - 1.0), 4.0 * (x[1] + 2.0)])


def hessp(x, p):
    return np.array([2.0 * p[0], 4.0 * p[1]])


def nonlinear(x):
    return np.array([x[0] ** 2 + x[1]])


def nonlinear_jac(x):
    return np.array([[2.0 * x[0], 1.0]])


def nonlinear_hess(x, v):
    return np.diag([2.0 * v[0], 0.0])


x0 = np.array([-1.0, 1.0])
tests = {
    "unconstrained": {},
    "linear": {"constraints": [LinearConstraint([[1, 1]], 0.0, 0.0)]},
    "bounds": {"bounds": Bounds([0.0, -2.0], [2.0, 0.0])},
    "nonlinear": {"constraints": [NonlinearConstraint(nonlinear, 0.0, 0.0,
                                               jac=nonlinear_jac, hess=nonlinear_hess)]},
}
output = [
    "! SPDX-License-Identifier: MIT",
    "! Generated by tools/generate_optimize_trust_constr_hessp_reference.py",
    f"! SciPy version: {scipy.__version__}",
    "module test_optimize_trust_constr_hessp_reference",
    "    use scifort_kinds, only : dp",
    "    implicit none",
]
for label, kwargs in tests.items():
    result = minimize(objective, x0, method="trust-constr", jac=gradient,
                      hessp=hessp, options={"gtol": 1e-9, "maxiter": 100}, **kwargs)
    assert result.success, (label, result.message)
    output.append(f"    real(dp), parameter :: {label}_x(2) = [ &")
    output.append(f"        {result.x[0]:.17e}_dp, {result.x[1]:.17e}_dp ]")
    output.append(f"    integer, parameter :: {label}_nit = {result.nit}")
    output.append(f"    integer, parameter :: {label}_nfev = {result.nfev}")
    output.append(f"    integer, parameter :: {label}_njev = {result.njev}")
    output.append(f"    integer, parameter :: {label}_nhev = {result.nhev}")
    print(label, result.x, result.nit, result.nfev, result.njev, result.nhev)
# Nonconstant Hessian with off-diagonal products verifies that the callback
# is re-evaluated at each iterate rather than cached at the starting point.
def rosenbrock(x):
    return 100.0 * (x[1] - x[0]**2)**2 + (1.0 - x[0])**2


def rosenbrock_gradient(x):
    return np.array([-400.0*x[0]*(x[1] - x[0]**2) - 2.0*(1.0 - x[0]),
                     200.0*(x[1] - x[0]**2)])


def rosenbrock_hessp(x, p):
    return np.array([(1200.0*x[0]**2 - 400.0*x[1] + 2.0)*p[0] - 400.0*x[0]*p[1],
                     -400.0*x[0]*p[0] + 200.0*p[1]])


rosen = minimize(rosenbrock, [-1.2, 1.0], method="trust-constr",
                 jac=rosenbrock_gradient, hessp=rosenbrock_hessp)
assert rosen.success
output.append("    real(dp), parameter :: rosenbrock_x(2) = [ &")
output.append(f"        {rosen.x[0]:.17e}_dp, {rosen.x[1]:.17e}_dp ]")
output.append(f"    integer, parameter :: rosenbrock_nit = {rosen.nit}")
output.append(f"    integer, parameter :: rosenbrock_nfev = {rosen.nfev}")
output.append(f"    integer, parameter :: rosenbrock_njev = {rosen.njev}")
output.append(f"    integer, parameter :: rosenbrock_nhev = {rosen.nhev}")
print("rosenbrock", rosen.x, rosen.nit, rosen.nfev, rosen.njev, rosen.nhev)
output.append("end module test_optimize_trust_constr_hessp_reference")
target = Path(__file__).resolve().parent.parent / "test/optimize_trust_constr_hessp_reference.f90"
target.write_text("\n".join(output) + "\n", encoding="ascii")
print("Generated:", target)
