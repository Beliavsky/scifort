#!/usr/bin/env python3
"""Generate SciPy 1.17 reference values for scalar minimization."""

from pathlib import Path
import scipy
from scipy import optimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def emit_result(parts, prefix, result):
    parts.append(f"    real(dp), parameter :: {prefix}_x_ref = {fmt(result.x)}\n")
    parts.append(f"    real(dp), parameter :: {prefix}_fun_ref = {fmt(result.fun)}\n")
    parts.append(f"    integer, parameter :: {prefix}_iterations_ref = {int(result.nit)}\n")
    parts.append(f"    integer, parameter :: {prefix}_calls_ref = {int(result.nfev)}\n")


def objective(x):
    return (x - 2.0) * x * (x + 2.0) ** 2


parts = [
    "! SPDX-License-Identifier: MIT\n",
    "! Generated by tools/generate_optimize_minimize_scalar_reference.py\n",
    f"! SciPy version: {scipy.__version__}\n",
    "module test_optimize_minimize_scalar_reference\n",
    "    use scifort_kinds, only : dp\n",
    "    implicit none\n",
]

r = optimize.minimize_scalar(objective, method="brent")
emit_result(parts, "brent_default", r)
r = optimize.minimize_scalar(objective, method="brent", bracket=(0.0, 1.0))
emit_result(parts, "brent_pair", r)
r = optimize.minimize_scalar(objective, method="brent", bracket=(0.0, 1.0, 3.0))
emit_result(parts, "brent_triple", r)
r = optimize.minimize_scalar(objective, method="golden", bracket=(0.0, 1.0))
emit_result(parts, "golden_pair", r)
r = optimize.minimize_scalar(objective, method="golden", bracket=(0.0, 1.0, 3.0))
emit_result(parts, "golden_triple", r)
r = optimize.minimize_scalar(objective, method="bounded", bounds=(-3.0, -1.0))
emit_result(parts, "bounded_default", r)
r = optimize.minimize_scalar(
    objective, method="bounded", bounds=(-3.0, -1.0), options={"xatol": 1.0e-10}
)
emit_result(parts, "bounded_tight", r)
r = optimize.minimize_scalar(
    objective, method="brent", bracket=(0.0, 1.0), options={"maxiter": 1}
)
emit_result(parts, "brent_maxiter1", r)
r = optimize.minimize_scalar(
    objective, method="golden", bracket=(0.0, 1.0), options={"maxiter": 1}
)
emit_result(parts, "golden_maxiter1", r)
r = optimize.minimize_scalar(
    objective, method="bounded", bounds=(-3.0, -1.0), options={"maxiter": 2}
)
emit_result(parts, "bounded_maxiter2", r)

parts.append("end module test_optimize_minimize_scalar_reference\n")

out = Path(__file__).resolve().parents[1] / "test" / "optimize_minimize_scalar_reference.f90"
out.write_text("".join(parts), encoding="ascii")
print(out)
