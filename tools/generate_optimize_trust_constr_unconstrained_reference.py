#!/usr/bin/env python3
"""Generate SciPy 1.17 references for unconstrained trust-constr."""

from pathlib import Path

import numpy as np
from scipy.optimize import minimize


def fmt(value):
    return f"{float(value):.17e}_dp"


def values(name, values_):
    vals = np.asarray(values_, dtype=float).ravel()
    return (f"    real(dp), parameter :: {name}({len(vals)}) = "
            f"[{', '.join(map(fmt, vals))}]")


def quadratic(x):
    return (x[0] - 1.0)**2 + 3.0 * (x[1] + 2.0)**2


def quadratic_jac(x):
    return np.array([2.0 * (x[0] - 1.0), 6.0 * (x[1] + 2.0)])


def quadratic_hess(x):
    return np.diag([2.0, 6.0])


def rosenbrock(x):
    return 100.0 * (x[1] - x[0]**2)**2 + (1.0 - x[0])**2


def rosenbrock_jac(x):
    return np.array([-400.0 * x[0] * (x[1] - x[0]**2) - 2.0 * (1.0 - x[0]),
                     200.0 * (x[1] - x[0]**2)])


def rosenbrock_hess(x):
    return np.array([[1200.0 * x[0]**2 - 400.0 * x[1] + 2.0, -400.0 * x[0]],
                     [-400.0 * x[0], 200.0]])


def main():
    cases = (
        ("exact", quadratic, quadratic_jac, quadratic_hess, [-1.0, 1.0], {}),
        ("numeric_gradient", quadratic, None, quadratic_hess, [-1.0, 1.0], {}),
        ("stationary", quadratic, quadratic_jac, quadratic_hess, [1.0, -2.0], {}),
        ("maxiter", quadratic, quadratic_jac, quadratic_hess, [-1.0, 1.0], {"maxiter": 1}),
        ("rosenbrock", rosenbrock, rosenbrock_jac, rosenbrock_hess, [-1.2, 1.0], {}),
    )
    lines = ["! SPDX-License-Identifier: MIT",
             "! Generated by tools/generate_optimize_trust_constr_unconstrained_reference.py",
             "! SciPy version: 1.17.0",
             "module test_optimize_trust_constr_unconstrained_reference",
             "    use scifort_kinds, only : dp",
             "    implicit none"]
    for name, f, jac, hess, start, options in cases:
        result = minimize(f, start, method="trust-constr", jac=jac, hess=hess,
                          options=options)
        assert result.status == (0 if name == "maxiter" else 1), result.message
        assert not result.constr and not result.v and not result.constr_nfev
        lines += [values(name + "_x", result.x),
                  f"    real(dp), parameter :: {name}_fun = {fmt(result.fun)}",
                  f"    integer, parameter :: {name}_nit = {result.nit}",
                  f"    integer, parameter :: {name}_nfev = {result.nfev}",
                  f"    integer, parameter :: {name}_njev = {result.njev}",
                  f"    integer, parameter :: {name}_nhev = {result.nhev}",
                  f"    integer, parameter :: {name}_cg_niter = {result.cg_niter}"]
    lines.append("end module test_optimize_trust_constr_unconstrained_reference")
    lines.append("")
    output = (Path(__file__).resolve().parent.parent / "test" /
              "optimize_trust_constr_unconstrained_reference.f90")
    output.write_text("\n".join(lines), encoding="ascii")
    print(output)


if __name__ == "__main__":
    main()
